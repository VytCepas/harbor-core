#!/usr/bin/env sh
# bin/doc-register-index.sh (harbor#1424): contracts/README.md and docs/reference/registers.md are generated, current, and
# change when a contract or a register is added. The red proofs: a contract added to a throwaway tree changes the index,
# an edited README is stale, --write restores it.
. "$(dirname "$0")/../../lib/core.sh"; t_init
GEN="$T_ROOT/bin/doc-register-index.sh"
R="$T_TMP/repo"
mkrepo() { rm -rf "$R"; mkdir -p "$R/contracts" "$R/standards/naming" "$R/docs/reference" "$R/bin"
  cp "$T_ROOT/bin/standard-register.sh" "$T_ROOT/bin/library-log.sh" "$R/bin/"
  cp "$T_ROOT/standards/naming/schemas.tsv" "$R/standards/naming/"
  printf '# index\n\n## Seams\n\nhand-kept prose\n\n<!-- gen:contract-files -->\n\nmore prose\n' > "$R/contracts/README.md.tmpl"
  printf '# Alpha — the first contract\n' > "$R/contracts/alpha.md"; printf '# beta.tsv (x) - the second\nid\tn\n' > "$R/contracts/beta.tsv"; }
g() { sh "$GEN" --root "$R" "$@" 2>&1; }

t_section "the real README mentions every file of contracts/"
_absent=0
for f in "$T_ROOT"/contracts/*; do b="$(basename "$f")"; [ "$b" = README.md ] && continue
  awk -v b="$b" 'index($0, b) { f = 1 } END { exit !f }' "$T_ROOT/contracts/README.md" || { _absent=$((_absent + 1)); echo "absent: $b" >&2; }; done
t_eq "contract files absent from contracts/README.md" 0 "$_absent"
t_exit "both generated files are current (--check)" 0 sh "$GEN" --check

t_section "a throwaway tree: the index follows the files"
mkrepo; g --write >/dev/null
t_has "an existing contract is a row" "$(cat "$R/contracts/README.md")" "[alpha.md](./alpha.md) | md | Alpha"
t_has "the narrative stays" "$(cat "$R/contracts/README.md")" "hand-kept prose"
t_has "the header says generated" "$(sed -n 1p "$R/contracts/README.md")" "generated by sh bin/doc-register-index.sh"
before="$(cat "$R/contracts/README.md")"
printf '# Gamma — added with no README edit\n' > "$R/contracts/gamma.md"
t_exit "a contract added makes --check red" 1 sh "$GEN" --root "$R" --check
g --write >/dev/null
t_has "and --write puts it in the index" "$(cat "$R/contracts/README.md")" "[gamma.md](./gamma.md)"
t_eq "...so the index changed" "changed" "$([ "$before" = "$(cat "$R/contracts/README.md")" ] && echo same || echo changed)"
t_exit "and is current again" 0 sh "$GEN" --root "$R" --check
ln -s alpha.md "$R/contracts/old-alpha.md"; g --write >/dev/null
t_has "a rename shim is a row, as a shim" "$(cat "$R/contracts/README.md")" "[old-alpha.md](./old-alpha.md) | shim"
echo 'hand edit' >> "$R/contracts/README.md"
t_exit "a hand edit makes --check red" 1 sh "$GEN" --root "$R" --check

t_section "the register index follows the schema table"
mkrepo; g --write >/dev/null
t_has "a register is a row" "$(cat "$R/docs/reference/registers.md")" '`standards/naming/controls.tsv`'
printf 'contracts/zz-new.tsv\trow\tid note\tid\t\tstandard\t-\ta register added later\n' >> "$R/standards/naming/schemas.tsv"
t_exit "a register added to the table makes --check red" 1 sh "$GEN" --root "$R" --check
g --write >/dev/null; t_has "and is in the index after --write" "$(cat "$R/docs/reference/registers.md")" 'contracts/zz-new.tsv'
rm "$R/contracts/README.md.tmpl"; t_exit "a missing template is unchecked (3)" 3 sh "$GEN" --root "$R" --check
t_done
