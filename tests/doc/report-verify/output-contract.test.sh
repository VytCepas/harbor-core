#!/usr/bin/env sh
# doc-report-verify.sh's output follows contracts/logging.md (harbor#1149): a header, an ok line per conforming artefact,
# a FAIL per broken property each followed by its fix, one summary, and 0 only when nothing failed.
. "$(dirname "$0")/../../lib/core.sh"; t_init
TOOL="$T_ROOT/bin/doc-report-verify.sh"
printf '# Report\nGenerated by a tool from a source.\nAs of 2026-10-11.\nNOT ENUMERATED: the rest.\n' > "$T_TMP/good.md"
printf '# Report\nGenerated by a tool from a source.\nAs of 2026-10-11.\n' > "$T_TMP/noscope.md"
printf '# Report\nNOT ENUMERATED: the rest.\n' > "$T_TMP/nosrc.md"
printf 'x\n' > "$T_TMP/thing.bin"; : > "$T_TMP/empty.md"
run() { "$@" >"$T_TMP/out" 2>"$T_TMP/err"; echo "exit $?"; }
OUT() { cat "$T_TMP/out"; }; ERR() { cat "$T_TMP/err"; }
nth_after_fail() { awk '/^  FAIL:/ { f = 1; next } f { print; exit }' "$T_TMP/out"; }

t_section "a conforming artefact"
t_eq "exit 0" "exit 0" "$(run sh "$TOOL" "$T_TMP/good.md")"
t_eq "the header names the contract" "── report-contract · contracts/reports.md properties 4 to 7" "$(OUT | head -1)"
t_eq "an ok line carries the path" "  ok: $T_TMP/good.md" "$(OUT | sed -n 2p)"
t_eq "the summary is last" "report-contract: 1 ok, 0 failed, 0 warnings" "$(OUT | tail -1)"
t_eq "stderr is empty" "" "$(ERR)"

t_section "a property missing: FAIL with the property id, its fix next, exit 1"
t_eq "no scope statement" "exit 1" "$(run sh "$TOOL" "$T_TMP/noscope.md")"
t_has "the FAIL names the property and the file" "$(OUT)" "  FAIL: $T_TMP/noscope.md: [4] states no limit on itself"
t_has "the next line is its fix" "$(nth_after_fail)" "  fix: add a section naming the classes it did not cover"
t_eq "no source" "exit 1" "$(run sh "$TOOL" "$T_TMP/nosrc.md")"
t_has "its FAIL is [5]" "$(OUT)" "[5] names no source"
t_has "and carries a fix" "$(nth_after_fail)" "  fix: name what it was generated from"
t_has "a missing date is its own FAIL" "$(OUT)" "[5] carries no ISO date"
t_eq "two findings are two FAIL lines, each with a fix" 2 "$(OUT | grep -c '^  fix: ')"
t_eq "and the summary counts them" "report-contract: 0 ok, 2 failed, 0 warnings" "$(OUT | tail -1)"

t_section "could not check is a FAIL too, and never an ok"
t_eq "an unreadable file" "exit 1" "$(run sh "$TOOL" "$T_TMP/absent.md")"
t_has "its FAIL" "$(OUT)" "  FAIL: $T_TMP/absent.md: could not check, unreadable"
t_has "its fix" "$(nth_after_fail)" "  fix: ls -l "
t_eq "an empty file" "exit 1" "$(run sh "$TOOL" "$T_TMP/empty.md")"
t_has "its FAIL" "$(OUT)" "could not check, empty"
t_has "its fix" "$(nth_after_fail)" "  fix: regenerate the artefact"
t_eq "a kind it has no rules for" "exit 1" "$(run sh "$TOOL" "$T_TMP/thing.bin")"
t_has "its FAIL" "$(OUT)" "could not check, no rules for this kind"
t_has "its fix" "$(nth_after_fail)" "  fix: sh "
t_eq "one bad file among good ones fails the run" "exit 1" "$(run sh "$TOOL" "$T_TMP/good.md" "$T_TMP/noscope.md")"
t_eq "and the summary counts both kinds" "report-contract: 1 ok, 1 failed, 0 warnings" "$(OUT | tail -1)"

t_section "usage is not a run"
t_eq "no argument exits 2" "exit 2" "$(run sh "$TOOL")"
t_has "usage on stderr" "$(ERR)" "usage:"
t_eq "with no summary" 0 "$(cat "$T_TMP/out" "$T_TMP/err" | grep -c 'failed, ')"

t_section "--self-test"
t_eq "it passes" "exit 0" "$(run sh "$TOOL" --self-test)"
t_has "a case is an ok line with its exit" "$(OUT)" "  ok: a file that does not exist exits 2, never 1 (exit 2)"
t_eq "the summary is the library's and counts no failure" 1 "$(OUT | tail -1 | grep -c '^report-contract: [0-9][0-9]* ok, 0 failed, 0 warnings$')"
t_eq "the old PASS shape is gone" 0 "$(OUT | grep -c '^  PASS  ')"
t_eq "and the case's own FAIL lines do not leak into the self-test's count" 0 "$(OUT | grep -c '^  FAIL:')"
t_done
