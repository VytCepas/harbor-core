#!/usr/bin/env sh
# standard.kind-fields (harbor#1424): bin/standard-shape.sh judges every catalog instance of a kind for the tokens its kinds.tsv
# row requires in required_fields. Each token is proven red on a file that lacks it and green on one that carries it; the
# red log names the rule, which is what the controls.tsv red_proof reads.
. "$(dirname "$0")/../../lib/core.sh"; t_init
TOOL="$T_ROOT/bin/standard-shape.sh"; REG="$T_ROOT/standards/naming"
R="$T_TMP/root"; mkdir -p "$R/docs" "$R/reg" "$R/skills/s"
cp "$REG/controls.tsv" "$R/reg/"; cp "$REG/terms.tsv" "$R/reg/"
awk -F'\t' -v OFS='\t' '$1 == "standard.kind-fields" { $2 = "warn" } { print }' "$R/reg/controls.tsv" > "$R/reg/c.tmp" && mv "$R/reg/c.tmp" "$R/reg/controls.tsv"
printf '# kinds\nid\trequired_fields\ndesign\tfront_matter\ndecision-record\tstatus\ncontract\tschema_version\ngenerated-doc\tgenerated-by\nregistry\tid-first why-header standard_version\nskill\tname description\nstandard\tmetadata.type\n' > "$R/kinds.tsv"
# an instance that carries every token, and one that carries none
printf -- '---\nstatus: accepted\nname: a\ndescription: b\nmetadata:\n  type: t\n---\n\n# good\n' > "$R/docs/good.md"
printf '# bad\nno front matter here\n' > "$R/docs/bad.md"
printf -- '---\nkind: x\n---\n# half\n' > "$R/docs/half.md"
printf '<!-- generated by sh bin/x.sh -->\n# g\n' > "$R/docs/gen-good.md"
printf '# STATUS\ngenerated, do not edit\n' > "$R/docs/gen-bad.md"
printf '# c\nschema_version: 1\n' > "$R/docs/c-good.md"
printf '# WHY: x\n# standard_version: 2.0.0\nid\tnote\nr\tn\n' > "$R/docs/reg-good.tsv"
printf 'a\tb\n' > "$R/docs/reg-bad.tsv"
printf -- '---\nname: s\n---\n' > "$R/skills/s/SKILL.md"; printf -- '---\nname: s\ndescription: d\n---\n' > "$R/skills/s/OK.md"
printf 'harbor:docs/good.md\tdesign\nharbor:docs/bad.md\tdesign\nharbor:docs/half.md\tdesign\nharbor:docs/good.md\tdecision-record\nharbor:docs/half.md\tdecision-record\nharbor:docs/gen-good.md\tgenerated-doc\nharbor:docs/gen-bad.md\tgenerated-doc\nharbor:docs/c-good.md\tcontract\nharbor:docs/bad.md\tcontract\nharbor:docs/reg-good.tsv\tregistry\nharbor:docs/reg-bad.tsv\tregistry\nharbor:skills/s/SKILL.md\tskill\nharbor:docs/good.md\tstandard\nharbor:docs/half.md\tstandard\ncontrol:name.case\tlint-rule\nharbor:docs/missing.md\tdesign\nharbor:README.md\tdesign\n' > "$R/targets.tsv"
run() { sh "$TOOL" --fields --root "$R" --registry "$R/reg" --kinds "$R/kinds.tsv" --targets "$R/targets.tsv" "$@" 2>&1; }
F() { run --all --format findings; }

t_section "each token is red where missing, green where carried"
out="$(F)"
t_has "front_matter: no block" "$out" "A	standard.kind-fields	harbor:docs/bad.md front_matter"
t_has "front_matter: an unclosed or absent block, not a key-less one" "$out" "A	standard.kind-fields	harbor:docs/bad.md front_matter"
t_hasnt "front_matter: a file with a block is green" "$out" "harbor:docs/good.md front_matter"
t_hasnt "front_matter: a block without the key is still a block" "$out" "harbor:docs/half.md front_matter"
t_has "a key: status absent from the block" "$out" "harbor:docs/half.md status"
t_hasnt "a key: status present" "$out" "harbor:docs/good.md status"
t_has "a dotted key: metadata.type absent" "$out" "harbor:docs/half.md metadata.type"
t_hasnt "a dotted key: metadata with an indented type" "$out" "harbor:docs/good.md metadata.type"
t_has "generated-by: a header that says only generated" "$out" "harbor:docs/gen-bad.md generated-by"
t_hasnt "generated-by: 'generated by' in the first lines" "$out" "harbor:docs/gen-good.md generated-by"
t_has "schema_version: absent" "$out" "harbor:docs/bad.md schema_version"
t_hasnt "schema_version: present" "$out" "harbor:docs/c-good.md schema_version"
t_has "why-header: a register with no WHY comment" "$out" "harbor:docs/reg-bad.tsv why-header"
t_has "standard_version: absent" "$out" "harbor:docs/reg-bad.tsv standard_version"
t_has "id-first: a header that does not open with id" "$out" "harbor:docs/reg-bad.tsv id-first"
t_hasnt "a register that carries all three is green" "$out" "harbor:docs/reg-good.tsv"
t_has "a skill's second key" "$out" "harbor:skills/s/SKILL.md description"

t_section "what is counted and not judged"
t_hasnt "a control row is not a file" "$out" "control:name.case"
t_hasnt "a missing file is not a finding" "$out" "docs/missing.md"
t_hasnt "a README is not an instance of a kind" "$out" "README.md"
t_has "they are counted" "$(run)" "not a file the fields can be read on"

t_section "the report is a count, not the census"
sum="$(run)"
t_has "a count per kind and token" "$sum" "design instance(s) lack front_matter"
t_has "the first instances are named" "$sum" "harbor:docs/bad.md"

t_section "the rule's mode decides the exit, and the red log names the rule"
t_exit "warn exits 0 on findings" 0 sh "$TOOL" --fields --root "$R" --registry "$R/reg" --kinds "$R/kinds.tsv" --targets "$R/targets.tsv"
awk -F'\t' -v OFS='\t' '$1 == "standard.kind-fields" { $2 = "block" } { print }' "$R/reg/controls.tsv" > "$R/reg/c.tmp" && mv "$R/reg/c.tmp" "$R/reg/controls.tsv"
t_exit "block exits 1 on findings" 1 sh "$TOOL" --fields --root "$R" --registry "$R/reg" --kinds "$R/kinds.tsv" --targets "$R/targets.tsv"
RED="$T_TMP/red"; : > "$RED"; LINT_REDLOG="$RED" sh "$TOOL" --fields --root "$R" --registry "$R/reg" --kinds "$R/kinds.tsv" --targets "$R/targets.tsv" >/dev/null 2>&1 || :
t_eq "LINT_REDLOG gets standard.kind-fields" "standard.kind-fields" "$(sort -u "$RED")"
printf 'harbor:docs/good.md\tdesign\n' > "$R/targets.tsv"
t_exit "a tree where every instance carries its fields exits 0 even in block" 0 sh "$TOOL" --fields --root "$R" --registry "$R/reg" --kinds "$R/kinds.tsv" --targets "$R/targets.tsv"

t_section "the real tree: the registry's tokens are the ones the judge reads"
t_exit "--fields on the real tree exits 0 (warn)" 0 sh "$TOOL" --fields
t_has "--list names the rule" "$(sh "$TOOL" --list)" "standard.kind-fields"
t_done
