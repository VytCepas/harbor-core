#!/usr/bin/env sh
# bin/lint-name.sh --gen validators and bin/name-check (harbor#1259): one anchored ERE per grammar-backed surface, derived
# from the registers, and the helper that answers with it. Works in a mini copy, so the break below never touches build/.
. "$(dirname "$0")/../../lib/core.sh"; t_init
# the suite never reads the box's private overlay (D-85)
HARBOR_SCOPE_PRIVATE="$TMP/no-private"; export HARBOR_SCOPE_PRIVATE; unset PORT_ROOT
. "$T_ROOT/tests/checks/lint-fixture.sh"
LN="$T_ROOT/bin/lint-name.sh"
REG="$T_ROOT/standards/naming"
. "$T_ROOT/tests/checks/lint.name-fixture.sh"
M="$TMP/validators"; mini "$M"; cp "$T_ROOT/bin/name-check" "$M/bin/"
V="$M/build/validators.txt"; NC="$M/bin/name-check"
SURF="$M/standards/naming/surfaces.tsv"

t_section "--gen validators writes one anchored ERE per grammar-backed surface, and no line for a prose surface"
t_exit "--gen validators exits 0" 0 sh "$M/bin/lint-name.sh" --root "$M" --gen validators
t_has "the file is marked as generated, not hand-written" "$(head -1 "$V")" "generated by bin/lint-name.sh --gen validators"
t_eq "one line per surface with a grammar cell, in surfaces.tsv order" \
  "$(awk -F'\t' '/^#/ || !H[FILENAME]++ { next } $6 != "-" && $6 != "" { printf "%s ", $1 }' "$SURF")" \
  "$(awk -F'\t' '!/^#/ { printf "%s ", $1 }' "$V")"
t_eq "a prose-rendered surface (path, case, release-tag) gets no validator" "" \
  "$(awk -F'\t' '$1 == "path" || $1 == "case" || $1 == "release-tag"' "$V")"
t_eq "every validator is an anchored ERE: ^ and \$ on every line" "" "$(awk -F'\t' '!/^#/ && ($2 !~ /^\^/ || $2 !~ /\$$/)' "$V")"
t_has "a Python test is allowed by the test validator (D-14)" "$(grep '^test[[:space:]]' "$V")" "test_[a-z][a-z0-9_]*"
t_has "a PATH command is allowed by the bin validator (D-11)" "$(grep '^bin[[:space:]]' "$V")" "|([a-z][a-z0-9]*(-[a-z][a-z0-9]*)*))\$"

t_section "every grammar surface's example conforms to its own validator"
for _s in bin skill test launchd env mcp-tool; do
  _ex="$(awk -F'\t' -v s="$_s" '$1 == s { print $5 }' "$SURF")"
  t_exit "$_s: name-check accepts its example $_ex" 0 sh "$NC" "$_s" "$_ex"
done

t_section "name-check exits 0 on a conforming string, 1 on a non-conforming one, 2 on usage or an unknown surface"
t_exit "a conforming string exits 0" 0 sh "$NC" bin admission-bash.sh
t_exit "a non-conforming string exits 1" 1 sh "$NC" bin Admission-Bash.sh
t_exit "a name whose first word is no family goes red" 1 sh "$NC" bin frobnicate-run.sh
t_has "…and the lint agrees: that is name.family" "$(sh "$LN" --root "$M" --check bin frobnicate-run.sh 2>&1)" "name.family"
t_exit "a PATH command with no extension conforms: it needs no family (D-11)" 0 sh "$NC" bin wait-for
t_exit "an empty string does not conform" 1 sh "$NC" bin ""
t_exit "a string with a space does not conform" 1 sh "$NC" bin "a b.sh"
t_exit "no arguments is a usage error, exit 2" 2 sh "$NC"
t_exit "one argument is a usage error, exit 2" 2 sh "$NC" bin
t_exit "three arguments is a usage error, exit 2" 2 sh "$NC" bin admission-bash.sh extra
t_exit "an unknown surface is exit 2" 2 sh "$NC" no-such-surface x
t_exit "a surface with no validator (its renderer is prose) is exit 2" 2 sh "$NC" path docs/reports/2026-10-03-review.md
t_exit "--help exits 0" 0 sh "$NC" --help
t_has "…and prints the usage line" "$(sh "$NC" --help)" "name-check <surface> <string>"

t_section "every conforming and non-conforming fixture of a grammar surface is judged as the lint judges it"
# A pass row conforms; a fail row of this surface's grammar rule must be refused; another rule's (case, alias, word) is the
# lint's own and only counted. Two readings sit outside the grammar: a test judges only test files (test_check), and
# launchd fixtures are written without the .plist the lint appends (check_rec).
for _s in bin skill test launchd env mcp-tool; do
  _rule="$(awk -F'\t' -v s="$_s" '$1 == s { print $6 }' "$SURF")"
  _pass=0; _fail=0; _skip=0; _mis=""
  for _side in pass fail; do
    awk -F'\t' '!/^#/ && $1 != "name" && NF >= 1 { print $1 "\t" $2 }' "$M/fixtures/naming/$_s/$_side/expect.tsv" > "$TMP/fx.$_s.$_side"
    while IFS='	' read -r _n _r; do
      _nm="$_n"; case "$_s:$_n" in launchd:*.plist) ;; launchd:*) _nm="$_n.plist" ;; esac
      if [ "$_s" = test ]; then case "${_n##*/}" in *.test.*|*-test.*|test_*.py|*_test.*) ;; *) _skip=$((_skip + 1)); continue ;; esac; fi
      sh "$NC" "$_s" "$_nm" > /dev/null 2>&1; _rc=$?
      if [ "$_side" = pass ]; then
        if [ "$_rc" -eq 0 ]; then _pass=$((_pass + 1)); else _mis="$_mis pass:$_nm=$_rc"; fi
      else
        case ",$_r," in *",$_rule,"*)
          if [ "$_rc" -eq 1 ]; then _fail=$((_fail + 1)); else _mis="$_mis fail:$_nm=$_rc"; fi ;;
        *) _skip=$((_skip + 1)) ;; esac
      fi
    done < "$TMP/fx.$_s.$_side"
  done
  t_eq "$_s: every pass fixture conforms and every shape fixture is refused ($_pass pass, $_fail refused, $_skip not this rule)" "" "$_mis"
  t_eq "$_s: the fixtures were read at all" yes "$( [ $((_pass + _fail)) -gt 0 ] && echo yes || echo no)"
done

t_section "a validator that rejects its example goes red: break it on disk, the self-test goes red, restore"
cp "$V" "$TMP/v-good"
sed -e '/^bin[[:space:]]/s/(access|admission|/(access|/' "$V" > "$TMP/v-broken" && cp "$TMP/v-broken" "$V"
t_exit "the broken file is not the derivation: the self-test exits 1" 1 sh -c 'sh "$1" --root "$2" --self-test > /dev/null 2>&1' _ "$M/bin/lint-name.sh" "$M"
_brk="$(sh "$M/bin/lint-name.sh" --root "$M" --self-test 2>&1)"
t_has "…and names the example its validator refuses" "$_brk" "bin its example admission-bash.sh does not match its validator"
t_has "…and says the file is not what the derivation gives" "$_brk" "build/validators.txt is not what --gen validators derives"
sh "$M/bin/lint-name.sh" --root "$M" --gen validators > /dev/null 2>&1
t_eq "restored by --gen validators, the file is byte-identical to the first derivation" "" "$(cmp "$V" "$TMP/v-good" 2>&1)"
_rst="$(sh "$M/bin/lint-name.sh" --root "$M" --self-test 2>&1)"
t_has "…and the self-test's validator checks are green again" "$_rst" "ok: build/validators.txt is what --gen validators derives"
t_hasnt "…with no validator line red" "$_rst" "FAIL: build/validators.txt"

t_section "a grammar cell that cannot be rendered refuses --gen validators, and names the surface"
BG="$TMP/badgrammar"; mini "$BG"
sed -e '/^bin[[:space:]]/s/<ext>/<extension>/' "$BG/standards/naming/surfaces.tsv" > "$TMP/surf.bad" && cp "$TMP/surf.bad" "$BG/standards/naming/surfaces.tsv"
t_exit "--gen validators exits 1 on the broken cell" 1 sh "$BG/bin/lint-name.sh" --root "$BG" --gen validators
t_has "…and says which surface and why" "$(sh "$BG/bin/lint-name.sh" --root "$BG" --gen validators 2>&1)" "--gen validators: bin: the slot <extension> is not a slot"
t_done
