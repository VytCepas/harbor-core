#!/usr/bin/env sh
# fixture.sh (harbor#1485) — the pane's test fixtures, from the real tools, as stdout: sh tests/status/suggest/fixture.sh <empty dir> > mods/status-pane/tests/fixtures/real-tools.ts
# The kit loads only code files, so the JSON rides in strings, byte for byte what the tools printed. e2e.test.sh holds the checked-in copy equal to this output.
set -eu
W="$1"
ROOT="$(CDPATH='' cd -- "$(dirname -- "$0")/../../.." && pwd)"
TREE="$W/tree"; CFG="$W/cfg"; ST="$W/state"
mkdir -p "$TREE/bin" "$TREE/context-rules/user" "$CFG/projects/-fx" "$ST" "$W/home"
cp "$ROOT/bin/status-suggest.sh" "$ROOT/bin/library-log.sh" "$ROOT/bin/library-fs.sh" "$TREE/bin/"
cp "$ROOT/fixtures/injection-rule/suggest-tool.tsv" "$TREE/context-rules/user/suggest-tool.tsv"
# The dates are the tool's clock; one fixed date keeps the fixture the same on any day.
fixdate() { sed "s/$(date +%Y-%m-%d)/2026-11-06/g"; }
real() { HOME="$W/home" HARBOR_STATUS_SUGGEST_DIR="$ST" sh "$TREE/bin/status-suggest.sh" "$@" 2>/dev/null; }

EMPTY="$(HOME="$W/home" HARBOR_STATUS_SUGGEST_DIR="$W/nothing" sh "$ROOT/bin/status-suggest.sh" status --json 2>/dev/null)"
real stop fixture-skill --origin agent
real stop a1b2c3d4 --origin panel
real shown fixture-verb
i=0; while [ "$i" -lt 20 ]; do real tick; i=$((i + 1)); done
STATUS="$(real status --json | fixdate)"

# Three repeated jobs, one of each kind the shapes reach, and one whose step holds a digit.
NOW="$(jq -n -r 'now | todate')"; n=0
call() { n=$((n + 1)); printf '{"type":"assistant","timestamp":"%s","message":{"content":[{"type":"tool_use","id":"i%s","name":"%s","input":%s}]}}\n' "$NOW" "$n" "$2" "$3" >> "$CFG/projects/-fx/$1.jsonl"; }
bash_() { call "$1" Bash "$(jq -cn --arg c "$2" '{command:$c}')"; }
for s in 1 2 3; do
  call "m$s" mcp__fixture__read_report '{}'; bash_ "m$s" 'docker ps'; call "m$s" mcp__fixture__read_report '{}'; bash_ "m$s" 'docker ps'
  call "s$s" mcp__fixture__read_report '{}'; call "s$s" Write '{"file_path":"/x/a.md"}'
  bash_ "j$s" 'python3 a.py'; bash_ "j$s" 'curl -s x.example'
done
SCAN="$(env -u CLAUDE_CONFIG_DIR HOME="$W/home" HARBOR_STATUS_SUGGEST_DIR="$W/nothing" sh "$ROOT/bin/status-suggest-scan.sh" --json --dir "$CFG" 2>/dev/null)"
VOCAB="$(sh "$ROOT/bin/status-suggest-scan.sh" --vocabulary 2>/dev/null)"

str() { printf '%s' "$1" | jq -Rs .; }
printf '// generated by tests/status/suggest/fixture.sh from the real tools; e2e.test.sh fails when this file and the tools part (harbor#1485)\n'
printf 'export const STATUS_EMPTY = %s\n' "$(str "$EMPTY")"
printf 'export const STATUS_ROWS = %s\n' "$(str "$STATUS")"
printf 'export const SCAN = %s\n' "$(str "$SCAN")"
printf 'export const VOCABULARY = %s\n' "$(str "$VOCAB")"
