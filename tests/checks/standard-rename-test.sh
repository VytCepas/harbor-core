  printf 'rename-0002\tGuides/one.md\tguides/one.md\tpath\tW1\t-\tcase only, in the directory\n' >> "$CR/standards/naming/renames.tsv"
  printf 'rename-0003\tGuides/two.md\tguides/three.md\tpath\tW1\t-\trenamed, in the re-cased directory\n' >> "$CR/standards/naming/renames.tsv"
