#!/usr/bin/env sh
# graph-gen.sh (harbor#996 A1, A2): the reference graph and `harbor refs`. Hermetic: a fixture box
# under the sandbox HOME (a harbor tree, a fleet tree, ~/.claude, ~/.local/bin, ~/Library/LaunchAgents),
# plus one read of the real tree for the git-grep equality. Every edge type has a lookalike that must
# stay out, because a graph that over-collects is as useless to a rename as one that misses.
. "$(dirname "$0")/../lib/core.sh"; t_init
TOOL="$T_ROOT/bin/graph-gen.sh"
command -v python3 >/dev/null 2>&1 || { t_section "python3 is absent"; t_exit "graph-gen is unchecked without python3" 3 sh "$TOOL"; t_done; }
H="$HOME"; CLAUDE_CONFIG_DIR="$H/.claude"; export CLAUDE_CONFIG_DIR
HB="$H/port/harbor"; FL="$H/port/projects-orchestrator"
mkdir -p "$HB/bin" "$HB/docs" "$HB/launchd" "$HB/tests" "$HB/vendor/skills/s" "$FL" "$H/.claude" "$H/.local/bin" "$H/Library/LaunchAgents"

# ── the harbor fixture tree
printf '#!/bin/sh\n. "$DIR/bin/lib.sh"\nlog_init alpha\necho "[check:alpha-check] ok"\n# [check:commented] a comment never emits\n' > "$HB/bin/a.sh"
printf '#!/bin/sh\n: lib\n' > "$HB/bin/lib.sh"
printf '#!/bin/sh\n: x\n' > "$HB/bin/x"
printf '#!/bin/sh\n: x-y\n' > "$HB/bin/x-y.sh"
printf '#!/bin/sh\n: generator\n' > "$HB/bin/status-gen.sh"
printf '#!/bin/sh\nlog_init demo\n' > "$HB/tests/t-test.sh"
printf 'a\0b\nsource bin/lib.sh\n' > "$HB/bin/nul.sh"   # a NUL: git grep calls it binary and still reports it
chmod +x "$HB/bin/a.sh" "$HB/bin/lib.sh" "$HB/bin/x" "$HB/bin/x-y.sh" "$HB/tests/t-test.sh"
printf '# readme\n' > "$HB/README.md"
printf 'see docs/README.md and bin/x-y.sh\nbin/a.sh then bin/a.sh again, one line\nfleet: projects-orchestrator/fleet.yaml\nlive: ~/.claude/bin/a.sh\n' > "$HB/docs/guide.md"
printf '# docs\n' > "$HB/docs/README.md"
printf '# STATUS — generated, do not edit\n\nRegenerate with `sh bin/status-gen.sh --apply`\n' > "$HB/STATUS.md"
{ i=1; while [ "$i" -lt 20 ]; do echo "line $i"; i=$((i+1)); done; echo 'STATUS.md is generated by bin/status-gen.sh'; } > "$HB/prose.md"
printf '<plist><string>~/.claude/bin/a.sh</string></plist>\n' > "$HB/launchd/com.x.job.plist"
printf '# s\n' > "$HB/vendor/skills/s/SKILL.md"
git -C "$HB" init -q && git -C "$HB" add -A
# ── a sibling: unqualified paths are its own, a harbor path is qualified
printf 'harbor wiring: harbor/bin/a.sh\nown: README.md\nunqualified bin/a.sh is NOT harbor'"'"'s\n' > "$FL/README.md"
printf 'fleet: []\n' > "$FL/fleet.yaml"
git -C "$FL" init -q && git -C "$FL" add -A
# ── the box: a manifest, the hooks, a link, an installed LaunchAgent
_blob() { git hash-object "$1"; }
{ echo '# .harbor-manifest: <git-blob> <mode> <relpath> <installer> <commit>'
  echo "$(_blob "$HB/bin/a.sh") 100755 bin/a.sh runtime-install c0"
  echo "$(_blob "$HB/vendor/skills/s/SKILL.md") 100644 skills/s/SKILL.md skills-install c0"
  echo "$(_blob "$HB/bin/lib.sh") 100755 hooks/renamed-lib.sh floor-install c0"
  echo "0000000000000000000000000000000000000000 100644 bin/gone.sh runtime-install c0"; } > "$H/.claude/.harbor-manifest"
printf '{"hooks":{"PreToolUse":[{"matcher":"Bash","hooks":[{"type":"command","command":"/bin/sh %s/.claude/bin/a.sh"}]}],\n"Stop":[{"hooks":[{"type":"command","command":"/bin/sh %s/.claude/hooks/renamed-lib.sh"}]}]}}\n' "$H" "$H" > "$H/.claude/settings.json"
ln -s "$HB/bin/x" "$H/.local/bin/x"
sed "s#~#$H#" "$HB/launchd/com.x.job.plist" > "$H/Library/LaunchAgents/com.x.job.plist"
printf 'not ours\n' > "$H/Library/LaunchAgents/com.other.plist"

G="$HB/build/graph.tsv"
gen() { sh "$TOOL" --root "$HB" "$@"; }
row() { awk -F'\t' -v e="$1" -v f="$2" -v t="$3" '$1 == e && $2 == f && $3 == t { n++ } END { print n + 0 }' "$G"; }  # <edge> <from> <to>
sites_eq() { # <path> — refs --sites against git grep -n -F, the done-when's own diff
  gen --refs --sites "$1" 2>/dev/null > "$T_TMP/a"; git -C "$HB" grep -n -F -e "$1" | cut -d: -f1,2 > "$T_TMP/b"
  [ -s "$T_TMP/b" ] && cmp -s "$T_TMP/a" "$T_TMP/b" && echo same || { diff "$T_TMP/a" "$T_TMP/b" >&2; echo differ; }
}

t_section "it builds, and every input says read or absent"
t_exit "a build exits" 0 gen
t_has "the harbor tree was read" "$(cat "$G")" "# input	harbor	~/port/harbor	14 files"
t_has "the fleet tree was read" "$(cat "$G")" "# input	fleet	~/port/projects-orchestrator	2 files"
t_has "an absent yard says absent" "$(cat "$G")" "# input	yard	~/port/project-init	absent"
t_has "the manifest counts its unresolved row" "$(cat "$G")" "4 rows, 1 unresolved"
t_has "the hooks are counted" "$(cat "$G")" "# input	settings	~/.claude/settings.json	2 hook commands"

t_section "same input, same bytes"
gen --stdout 2>/dev/null > "$T_TMP/g1"; gen --stdout 2>/dev/null > "$T_TMP/g2"
t_eq "two builds are byte-identical" same "$(cmp -s "$T_TMP/g1" "$T_TMP/g2" && echo same || echo differ)"
t_eq "--stdout is the file a build writes" same "$(cmp -s "$T_TMP/g1" "$G" && echo same || echo differ)"

t_section "--check: green when current, RED when stale or absent"
t_exit "a current graph" 0 gen --check
printf 'new: bin/lib.sh\n' >> "$HB/docs/guide.md"
t_exit "a tree that moved under the graph is stale" 1 gen --check
t_has "the stale line counts the drift" "$(gen --check 2>&1)" "adds 1 rows and drops 0"
gen >/dev/null 2>&1
t_exit "a rebuild is current again" 0 gen --check
rm -f "$G"
t_exit "an absent graph is not current" 1 gen --check
gen >/dev/null 2>&1

t_section "references: refs --sites diffs to nothing against git grep -n -F"
for p in bin/x bin/x-y.sh README.md docs/README.md bin/a.sh bin/lib.sh; do
  t_eq "$p" same "$(sites_eq "$p")"
done
t_eq "bin/x is inside bin/x-y.sh, to grep and to the graph" 1 "$(row references harbor:docs/guide.md harbor:bin/x)"
t_eq "a path twice on one line is one site" 1 "$(gen --refs --sites bin/a.sh 2>/dev/null | grep -c '^docs/guide.md:2$')"
t_has "a binary file is git grep's own line" "$(gen --refs --sites bin/lib.sh 2>/dev/null)" "Binary file bin/nul.sh matches"

t_section "references across trees: qualified only"
t_eq "harbor/bin/a.sh in fleet reaches harbor" 1 "$(row references fleet:README.md harbor:bin/a.sh)"
t_eq "fleet's own README.md is fleet's" 1 "$(row references fleet:README.md fleet:README.md)"
t_eq "projects-orchestrator/fleet.yaml in harbor reaches fleet" 1 "$(row references harbor:docs/guide.md fleet:fleet.yaml)"
t_eq "an unqualified bin/a.sh in fleet is NOT harbor's" 0 "$(awk -F'\t' '$1=="references" && $2=="fleet:README.md" && $3=="harbor:bin/a.sh" && $4=="fleet:README.md:3"' "$G" | wc -l | tr -d ' ')"

t_section "deploys_to: the manifest, ~/.local/bin, LaunchAgents"
t_eq "a manifest row" 1 "$(row deploys_to harbor:bin/a.sh '~/.claude/bin/a.sh')"
t_eq "a vendored skill resolves to vendor/" 1 "$(row deploys_to harbor:vendor/skills/s/SKILL.md '~/.claude/skills/s/SKILL.md')"
t_eq "an unknown row is ?" 1 "$(row deploys_to '?' '~/.claude/bin/gone.sh')"
t_eq "a ~/.local/bin link" 1 "$(row deploys_to harbor:bin/x '~/.local/bin/x')"
t_eq "an installed LaunchAgent with a twin" 1 "$(row deploys_to harbor:launchd/com.x.job.plist '~/Library/LaunchAgents/com.x.job.plist')"
t_eq "a LaunchAgent with no twin is not ours" 0 "$(grep -c 'com.other' "$G" || :)"
t_eq "the installed plist wires the deployed script" 1 "$(row references '~/Library/LaunchAgents/com.x.job.plist' '~/.claude/bin/a.sh')"
t_eq "settings.json wires the deployed script" 1 "$(row references '~/.claude/settings.json' '~/.claude/bin/a.sh')"
R="$(gen --refs bin/a.sh 2>/dev/null)"
t_has "refs follows the deploy one hop to the hook line" "$R" "~/.claude/settings.json:1"
t_has "and to the LaunchAgent" "$R" "~/Library/LaunchAgents/com.x.job.plist:1"
t_eq "a copy deployed under another name resolves by its bytes" 1 "$(row deploys_to harbor:bin/lib.sh '~/.claude/hooks/renamed-lib.sh')"
t_has "and its hook line is listed under the source, through the hop alone" "$(gen --refs bin/lib.sh 2>/dev/null)" "~/.claude/settings.json:2"
rm "$H/.claude/.harbor-manifest"; gen >/dev/null 2>&1
t_eq "no manifest, no manifest edge" 0 "$(row deploys_to harbor:bin/a.sh '~/.claude/bin/a.sh')"
t_has "and the input says absent" "$(cat "$G")" "# input	manifest	~/.claude/.harbor-manifest	absent"

t_section "emits: code stamps, never a comment or a test"
t_eq "log_init alpha" 1 "$(row emits harbor:bin/a.sh log:alpha)"
t_eq "[check:alpha-check]" 1 "$(row emits harbor:bin/a.sh check:alpha-check)"
t_eq "a commented stamp is not emitted" 0 "$(grep -c 'check:commented' "$G" || :)"
t_eq "a test's log_init is not emitted" 0 "$(grep -c 'log:demo' "$G" || :)"
t_eq "an id answers refs by its bare name" 1 "$(gen --refs alpha-check 2>/dev/null | grep -c '^emits')"

t_section "derives_from: the file's own header, not prose about it"
t_eq "STATUS.md names its generator" 1 "$(row derives_from harbor:STATUS.md harbor:bin/status-gen.sh)"
t_eq "prose at line 20 does not" 0 "$(row derives_from harbor:prose.md harbor:bin/status-gen.sh)"

t_section "usage and the door"
t_exit "an unknown node" 1 gen --refs bin/nope.sh
t_exit "--refs with nothing" 2 gen --refs
t_exit "--sites without --refs" 2 gen --sites
t_exit "an unknown option" 2 gen --bogus
gen --refs --sites bin/a.sh 2>/dev/null > "$T_TMP/a"
sh "$T_ROOT/bin/harbor" refs --root "$HB" --sites bin/a.sh 2>/dev/null > "$T_TMP/d"
t_eq "harbor refs is the same answer" same "$([ -s "$T_TMP/a" ] && cmp -s "$T_TMP/a" "$T_TMP/d" && echo same || echo differ)"

t_section "the real tree: refs --sites equals git grep for its most-wired paths"
REAL="$T_TMP/real"; mkdir -p "$REAL"
for p in bin/guard-bash.sh bin/guard-lib.sh bin/harbor README.md CONTRACTS/suites.txt bin/log-lib.sh; do
  sh "$TOOL" --out "$REAL/graph.tsv" --refs --sites "$p" 2>/dev/null > "$REAL/a"; git -C "$T_ROOT" grep -n -F -e "$p" | cut -d: -f1,2 > "$REAL/b"
  t_eq "$p ($(wc -l < "$REAL/b" | tr -d ' ') sites)" same "$([ -s "$REAL/b" ] && cmp -s "$REAL/a" "$REAL/b" && echo same || echo differ)"
done
t_done
