#!/usr/bin/env sh
# The live-change guard (harbor#1541): a label from contracts/live-change-words.txt is refused on click, and on Enter, Space
# and --submit when the focused control or its form's submit button carries one, on both routes: the MCP server against the
# fake daemon, the shell agent against the stub CLI. A refusal is proved by the call log, never by the message alone.
REQ_BUN="${HARBOR_TEST_REQUIRE_BUN:-0}"  # before t_init clears it
. "$(dirname "$0")/../../lib/core.sh"; t_init
. "$(dirname "$0")/server-env.sh"

t_section "server: a commit label is refused on click, phrases and Lithuanian capitals included"
clean; : > "$CALLS"
t_eq "Save changes is refused" "exit 1" "$(mcp click e24)"
t_has "...naming the word" "$(txt)" "matches 'save'"
t_has "...with confirm_click as the way through" "$(txt)" 'mcp__harbor_chrome__confirm_click with args ["e24"]'
t_eq "Turn on is refused (a phrase)" "exit 1" "$(mcp click e25)"
t_has "...as the phrase" "$(txt)" "matches 'turn on'"
t_eq "ĮJUNGTI is refused (Į folds to į)" "exit 1" "$(mcp click e26)"
t_eq "none of them reached the daemon" 0 "$(n '^script click e2[456]\|^click e2[456]')"
t_eq "status text passes (Saved, Applied: whole words)" "exit 0" "$(mcp click e27)"
jq -n '{permissions: {ask: ["mcp__harbor_chrome__confirm_click"]}}' > "$SETF"
t_eq "confirm_click runs a Save" "exit 0" "$(mcp confirm_click e24)"
t_eq "...once" 1 "$(n '^script click e24')"

t_section "server: Enter, Space and --submit ask what they would commit"
clean; : > "$CALLS"; printf 'Publish' > "$CTL/submit_label"
t_eq "press Enter on a Publish button is refused" "exit 1" "$(mcp press Enter)"
t_has "...as a hand-off naming the label" "$(txt)" "hand-off: destructive press refused: 'Enter' would commit 'Publish', which matches 'publish'"
t_eq "...after the focus probe, raw" 1 "$(n '^probe submit \[raw\]')"
t_eq "...and the key never reached the daemon" 0 "$(n '^press')"
t_eq "Control+Enter is the same commit" "exit 1" "$(mcp press Control+Enter)"
t_eq "Space too" "exit 1" "$(mcp press Space)"
t_eq "keydown Enter too" "exit 1" "$(mcp keydown Enter)"
t_eq "type --submit too" "exit 1" "$(mcp type hello --submit)"
t_eq "fill --submit too" "exit 1" "$(mcp fill e9 x --submit)"
t_eq "...probing its ref" 1 "$(n '^probe submit e9 \[raw\]')"
t_eq "fill --submit on a selector is refused (no label to check)" "exit 1" "$(mcp fill 'text=Name' x --submit)"
t_eq "inside steps too" "exit 1" "$(steps() { _r="$(printf '%s\n' "$(jq -cn '{jsonrpc:"2.0",id:9,method:"tools/call",params:{name:"steps",arguments:{steps:[{verb:"press",args:["Enter"]}]}}}')" | envs bun "$SRV" 2>&1)"; [ "$(printf '%s' "$_r" | jq -r .result.isError)" = false ] && echo "exit 0" || echo "exit 1"; }; steps)"
t_eq "none of those reached the daemon" 0 "$(n '^press\|^keydown\|^type\|^fill')"
: > "$CALLS"; printf 'Search' > "$CTL/submit_label"
t_eq "Enter on a Search form goes through" "exit 0" "$(mcp press Enter)"
t_eq "...to the daemon" 1 "$(n '^press Enter')"
t_eq "fill --submit on it goes through" "exit 0" "$(mcp fill e9 x --submit)"
: > "$CALLS"
t_eq "a letter key is not probed" "exit 0" "$(mcp press a)"
t_eq "...no probe ran" 0 "$(n '^probe submit')"
t_eq "plain fill is not probed" "exit 0" "$(mcp fill e9 x)"
t_eq "...no probe ran" 0 "$(n '^probe submit')"
: > "$CTL/submit_fail"; : > "$CALLS"
t_eq "a probe that cannot answer refuses" "exit 1" "$(mcp press Enter)"
t_eq "...and the key never went" 0 "$(n '^press')"
clean

t_section "server: a missing list refuses every guarded verb, and the guard line can fail"
mv "$X/contracts/live-change-words.txt" "$T_TMP/lcw.keep"; : > "$CALLS"
t_eq "an ordinary click is refused with no list" "exit 1" "$(mcp click e3)"
t_has "...naming the file" "$(txt)" "contracts/live-change-words.txt is missing or empty"
printf 'Search' > "$CTL/submit_label"
t_eq "Enter is refused with no list" "exit 1" "$(mcp press Enter)"
t_eq "nothing reached the daemon" 0 "$(n '^script click\|^press')"
mv "$T_TMP/lcw.keep" "$X/contracts/live-change-words.txt"; clean
mkdir -p "$T_TMP/lmut/bin" "$T_TMP/lmut/contracts"; cp "$X/bin/access-chrome-mcp.seams.json" "$X/bin/access-browser-agent.sh" "$X/bin/scope-roots.sh" "$X/bin/access-redact.sh" "$X/bin/admission-egress.sh" "$T_TMP/lmut/bin/"; cp "$X/contracts/"* "$T_TMP/lmut/contracts/"
sed 's/^  await submitGuard(c, S, wd, verb, args);$/  \/\/ removed/' "$SRV" > "$T_TMP/lmut/bin/access-chrome-mcp.ts"
t_eq "CONTROL: the mutant differs from the server" yes "$(cmp -s "$SRV" "$T_TMP/lmut/bin/access-chrome-mcp.ts" || echo yes)"
_old="$SRV"; SRV="$T_TMP/lmut/bin/access-chrome-mcp.ts"; printf 'Publish' > "$CTL/submit_label"; : > "$CALLS"
t_eq "without the submit guard, Enter on Publish goes through" "exit 0" "$(mcp press Enter)"
SRV="$_old"; clean

t_section "server: a Copy click with no window is refused: that Chrome's clipboard is not the operator's (2026-11-23)"
cat >> "$SNAP" <<'EOF'
  - button "Copy & Close" [ref=e28] [box=8,230,80,20]
  - button "Copy API key \"Example API\" to clipboard" [ref=e29] [box=100,230,80,20]
  - button "Copy campaign" [ref=e30] [box=200,230,80,20]
  - button "Copy token" [ref=e33] [box=300,230,80,20]
  - button "Paste from clipboard" [ref=e34] [box=400,230,80,20]
EOF
mkdir -p "$WD"; rm -f "$WD/.shown"; : > "$WD/.agent"; : > "$CALLS"
t_eq "Copy & Close (RTB House) is refused in the headless agent Chrome" "exit 1" "$(mcp click e28)"
t_has "...naming the label" "$(txt)" "copy click refused: 'button \"Copy & Close\"' (e28)"
t_has "...and the intake verb as the way" "$(txt)" "use harbor chrome intake e28 rotate <id>"
t_eq "Copy API key ... to clipboard (a partner UI, measured) is refused" "exit 1" "$(mcp click e29)"
t_eq "...by name too" "exit 1" "$(mcp click '--text=Copy & Close')"
t_eq "...and past confirm_click: a confirm reaches no clipboard" "exit 1" "$(mcp confirm_click e28)"
t_eq "none of them reached the daemon" 0 "$(n 'click e2[89]')"
t_eq "Copy campaign passes headless: a duplicate, not a copy" "exit 0" "$(mcp click e30)"
t_eq "Copy token, naming no clipboard, is refused" "exit 1" "$(mcp click e33)"
t_eq "Paste from clipboard passes headless: it copies nothing" "exit 0" "$(mcp click e34)"
cp "$CTL/submit_label" "$T_TMP/sl0" 2>/dev/null || rm -f "$T_TMP/sl0"; printf 'Copy & Close' > "$CTL/submit_label"; : > "$CALLS"
t_eq "Enter on a focused Copy & Close is refused headless" "exit 1" "$(mcp press Enter)"
t_has "...as a copy key" "$(txt)" "copy key refused"
t_eq "...and never reached the daemon" 0 "$(n 'press Enter')"
if [ -e "$T_TMP/sl0" ]; then mv "$T_TMP/sl0" "$CTL/submit_label"; else rm -f "$CTL/submit_label"; fi
rm -f "$WD/.agent"; : > "$WD/.headless"
t_eq "the headless lane refuses it too" "exit 1" "$(mcp click e28)"
t_has "...as the copy click" "$(txt)" "copy click refused"
rm -f "$WD/.headless"; : > "$CALLS"
t_eq "the operator's Chrome is not refused" "exit 0" "$(mcp click e28)"
t_eq "...the click reached the daemon" 1 "$(n '^script click e28')"
: > "$WD/.agent"; : > "$WD/.shown"; : > "$CALLS"
t_eq "after attach --show (.shown) the same click passes" "exit 0" "$(mcp click e28)"
t_eq "...and the clipboard one" "exit 0" "$(mcp click e29)"
t_eq "...both reaching the daemon" 2 "$(n '^script click e2[89]')"
rm -f "$WD/.shown"; : > "$CALLS"
t_eq "intake is the shell agent's: the value never passes through this server" "exit 0" "$(mcp intake e28 rotate rtbhouse-api-analytics)"
t_has "...its args reach the agent as a list" "$(txt)" "$(printf 'arg=intake\narg=e28\narg=rotate\narg=rtbhouse-api-analytics')"
t_has "...as an agent's call" "$(txt)" "enforce=1"
t_eq "...and the server sent the daemon nothing" 0 "$(grep -c . "$CALLS")"
sed 's/ \&\& noWindow(wd) \&\& copyClick(lab)) refuse(/ \&\& false) refuse(/' "$SRV" > "$T_TMP/lmut/bin/access-chrome-mcp.ts"
t_eq "CONTROL: the copy mutant differs from the server" yes "$(cmp -s "$SRV" "$T_TMP/lmut/bin/access-chrome-mcp.ts" || echo yes)"
_old="$SRV"; SRV="$T_TMP/lmut/bin/access-chrome-mcp.ts"; : > "$CALLS"
t_eq "without the copy guard, Copy & Close goes through headless" "exit 0" "$(mcp click e28)"
SRV="$_old"; rm -f "$WD/.agent"; clean

t_section "shell agent: the same list and the same probe"
AGENT="$T_ROOT/bin/access-browser-agent.sh"; CALLS="$T_TMP/calls"; : > "$CALLS"
t_eq "Save changes is refused" "exit 1" "$(ag click e24)"
t_has "...naming the word" "$(out)" "matches 'save'"
t_eq "Turn on is refused" "exit 1" "$(ag click e25)"
t_eq "ĮJUNGTI is refused" "exit 1" "$(ag click e26)"
t_eq "status text passes" "exit 0" "$(ag click e27)"
t_eq "press Enter on Publish is refused" "exit 1" "$(STUB_SUBMIT_LABEL=Publish; export STUB_SUBMIT_LABEL; ag press Enter)"
t_has "...naming the label" "$(out)" "'Enter' would commit 'Publish', which matches 'publish'"
t_eq "fill --submit on Save is refused" "exit 1" "$(STUB_SUBMIT_LABEL='Save'; export STUB_SUBMIT_LABEL; ag fill e9 x --submit)"
t_eq "the Enter never reached the CLI" 0 "$(called ' press Enter')"
t_eq "...nor the fill" 0 "$(called ' fill e9')"
t_eq "Enter on Search goes through" "exit 0" "$(STUB_SUBMIT_LABEL=Search; export STUB_SUBMIT_LABEL; ag press Enter)"
t_eq "...to the CLI" 1 "$(called ' press Enter')"
t_eq "a probe that cannot answer refuses" "exit 1" "$(STUB_SUBMIT_FAIL=1; export STUB_SUBMIT_FAIL; ag press Enter)"
M="$T_TMP/agmut"; mkdir -p "$M/bin" "$M/contracts"; cp "$AGENT" "$T_ROOT/bin/library-log.sh" "$T_ROOT/bin/access-redact.sh" "$T_ROOT/bin/admission-egress.sh" "$M/bin/"; cp "$T_ROOT/contracts/browser-agent-hosts.txt" "$T_ROOT/contracts/browser-script.tsv" "$M/contracts/"
_oa="$AGENT"; AGENT="$M/bin/access-browser-agent.sh"
t_eq "with no list the shell agent refuses an ordinary click" "exit 1" "$(ag click e3)"
t_has "...naming the file" "$(out)" "contracts/live-change-words.txt is missing or empty"
cp "$T_ROOT/contracts/live-change-words.txt" "$M/contracts/"
sed 's/^    case "$VERB" in press|keydown|type|fill) _submit_guard "$@" ;; esac$/    : removed/' "$_oa" > "$M/bin/access-browser-agent.sh"
t_eq "CONTROL: the shell mutant differs" yes "$(cmp -s "$_oa" "$M/bin/access-browser-agent.sh" || echo yes)"
t_eq "without the submit guard, the shell agent sends Enter on Publish" "exit 0" "$(STUB_SUBMIT_LABEL=Publish; export STUB_SUBMIT_LABEL; ag press Enter)"
AGENT="$_oa"
t_done
