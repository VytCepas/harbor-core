#!/usr/bin/env sh
# doc-register-index.sh (harbor#1424) — the two indexes over the registers and the contracts, generated and never hand-written.
#
#   sh bin/doc-register-index.sh --write          write contracts/README.md and docs/reference/registers.md
#   sh bin/doc-register-index.sh --check          exit 1 when either is not what the generator makes (the fresh-check rows)
#   sh bin/doc-register-index.sh --print <index>  one index on stdout: contracts | registers
#   sh bin/doc-register-index.sh --help
#   --root <dir>   the tree to read and write (default: this checkout)
#
# contracts/README.md is contracts/README.md.tmpl with its <!-- gen:contract-files --> hole filled by one row per file in
# contracts/ (a name, a kind, the title its first heading or first comment line gives): the narrative is hand-kept in the
# template, the index of what exists is derived, so a contract added without a README edit appears anyway.
# docs/reference/registers.md is the schema table (standards/naming/schemas.tsv) as one table, from bin/standard-register.sh index.
#
# exit 0 written / current · 1 stale (--check) · 2 usage · 3 unchecked (a source is missing)
set -eu
case "$0" in */*) HERE="${0%/*}" ;; *) HERE=. ;; esac
HERE="$(CDPATH='' cd -- "$HERE" && pwd)"
# shellcheck disable=SC2034 # LOG_FD: read by library-log.sh
LOG_FD=2
. "$HERE/library-log.sh"
log_init register-index
usage() { awk 'NR < 2 { next } !/^#/ { exit } { sub(/^# ?/, ""); print }' "$HERE/${0##*/}"; }
die2() { log_fail "$1"; log_fix "sh $HERE/${0##*/} --help"; log_end || :; exit 2; }

ACTION=""; WHICH=""; ROOT=""
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --write) ACTION=write ;;
    --check) ACTION=check ;;
    --print) ACTION=print; [ $# -ge 2 ] || die2 "--print needs contracts or registers"; WHICH="$2"; shift ;;
    --root) [ $# -ge 2 ] || die2 "--root needs a directory"; ROOT="$2"; shift ;;
    *) die2 "unknown argument: $1" ;;
  esac
  shift
done
[ -n "$ACTION" ] || die2 "no action"
ROOT="${ROOT:-$HERE/..}"
ROOT="$(CDPATH='' cd -- "$ROOT" 2>/dev/null && pwd -P)" || die2 "--root is not a directory"
T="$(mktemp -d "${TMPDIR:-/tmp}/register-index.XXXXXX")"
trap 'rm -rf "$T"' EXIT INT TERM HUP

# title <file> → what the file says it is: its first heading, else its first comment line, minus the file's own name
title() {
  awk -v n="${1##*/}" '
    function clean(s) { sub(/^[#\t ]+/, "", s); sub(/^`?/, "", s); gsub(/\|/, "\\|", s); gsub(/[ \t]+$/, "", s); return s }
    NR > 40 { exit }
    /^---$/ { next }
    /^# / { t = clean($0); if (t != "") { print substr(t, 1, 140); done = 1; exit } }
    /^#[^ !]/ { next }
    END { if (!done) print "-" }' "$1"
}
gen_contracts() {
  [ -f "$ROOT/contracts/README.md.tmpl" ] || return 3
  {
    printf '| File | Kind | What it is |\n|---|---|---|\n'
    find "$ROOT/contracts" -maxdepth 1 \( -type f -o -type l \) ! -name README.md ! -name README.md.tmpl | LC_ALL=C sort | while IFS= read -r _f; do
      _b="${_f##*/}"; _k="${_b##*.}"
      if [ -L "$_f" ]; then printf '| [%s](./%s) | shim | the old name of `%s` (renames.tsv), kept until its remove_by date |\n' "$_b" "$_b" "$(readlink "$_f" | sed 's#.*/##')"
      else printf '| [%s](./%s) | %s | %s |\n' "$_b" "$_b" "$_k" "$(title "$_f")"; fi
    done
  } > "$T/files.md"
  awk -v hole="$T/files.md" '
    BEGIN { print "<!-- generated by sh bin/doc-register-index.sh --write from contracts/README.md.tmpl and the files here — do not edit -->"; print "<!-- generated-by: sh bin/doc-register-index.sh --write -->" }
    $0 == "<!-- gen:contract-files -->" { while ((getline l < hole) > 0) print l; close(hole); n++; next }
    { print }
    END { if (n != 1) exit 3 }' "$ROOT/contracts/README.md.tmpl"
}
gen_registers() {
  [ -f "$ROOT/standards/naming/schemas.tsv" ] || return 3
  cat <<'HDR'
---
kind: reference
owner: harbor#1424
status: generated
---
<!-- generated by sh bin/doc-register-index.sh --write from standards/naming/schemas.tsv — do not edit -->
<!-- generated-by: sh bin/doc-register-index.sh --write -->

# Registers

Every `.tsv` register in the tree, with the columns, key and references its row in `standards/naming/schemas.tsv` declares.
Read one by column name with `sh bin/standard-register.sh get <file> <column>...`; a register with no row, a row with no file and a
reference to an id that is not there are each red (`standard.register-declared`, `standard.reference-resolves`).

HDR
  sh "$HERE/standard-register.sh" --root "$ROOT" index
}
produce() { # <index> <out>
  case "$1" in
    contracts) gen_contracts > "$2" ;;
    registers) gen_registers > "$2" ;;
  esac
}
dest() { case "$1" in contracts) echo "$ROOT/contracts/README.md" ;; registers) echo "$ROOT/docs/reference/registers.md" ;; esac; }

case "$ACTION" in
  print)
    case "$WHICH" in contracts|registers) ;; *) die2 "--print takes contracts or registers" ;; esac
    _rc=0; produce "$WHICH" "$T/out" || _rc=$?
    [ "$_rc" -eq 0 ] || { log_fail "a source for the $WHICH index is missing or malformed"; log_fix "ls $ROOT/contracts/README.md.tmpl $ROOT/standards/naming/schemas.tsv"; log_end || :; exit 3; }
    cat "$T/out" ;;
  write|check)
    _stale=0
    for _i in contracts registers; do
      _rc=0; produce "$_i" "$T/$_i" || _rc=$?
      [ "$_rc" -eq 0 ] || { log_fail "a source for the $_i index is missing or malformed"; log_fix "ls $ROOT/contracts/README.md.tmpl $ROOT/standards/naming/schemas.tsv"; log_end || :; exit 3; }
      _d="$(dest "$_i")"
      if [ "$ACTION" = write ]; then mkdir -p "${_d%/*}"; cp "$T/$_i" "$_d"; log_ok "wrote ${_d#"$ROOT"/}"
      elif cmp -s "$T/$_i" "$_d"; then log_ok "${_d#"$ROOT"/} is current"
      else _stale=$((_stale + 1)); log_fail "${_d#"$ROOT"/} is STALE"; log_fix "sh bin/doc-register-index.sh --write"; fi
    done
    log_end || :; [ "$_stale" -eq 0 ] ;;
esac
