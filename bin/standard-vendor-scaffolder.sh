#!/usr/bin/env sh
# standard-vendor-scaffolder.sh (harbor#1278) — vendors the scaffolder templates a member laptop renders and holds the copy to the scaffolder.
# --write copies them into vendor/scaffolder/ with a manifest; --check is red on drift (check standard.vendor-scaffolder-fresh).
set -u
LC_ALL=C; export LC_ALL
case "$0" in */*) SRC="${0%/*}" ;; *) SRC=. ;; esac
SRC="$(CDPATH= cd -- "$SRC" && pwd -P)"
# shellcheck disable=SC2034 # LOG_FD: read by library-log.sh
LOG_FD=2; . "$SRC/library-log.sh"; log_init standard-vendor-scaffolder
TAB="$(printf '\t')"
FILES="templates/base/AGENTS.md.tmpl templates/base/CLAUDE.md.tmpl"
ROOT="$(CDPATH= cd -- "$SRC/.." && pwd -P)"; DEST="$ROOT/vendor/scaffolder"; MAN="$DEST/MANIFEST.tsv"

die() { log_fail "$1"; log_fix "${2:-sh $0 --help}"; log_end || :; exit 2; }
usage() {
  cat <<'EOF_USAGE'

  sh standard-vendor-scaffolder.sh --write [--yard <dir>]   copy yard's templates/base/AGENTS.md.tmpl and CLAUDE.md.tmpl into vendor/scaffolder/
                                                      and write vendor/scaffolder/MANIFEST.tsv (yard commit, sha256, source)
  sh standard-vendor-scaffolder.sh --check [--yard <dir>]   is the vendored copy what yard has now: edited (differs from its manifest row),
                                                      stale (differs from yard), missing or extra
  default yard: <workspace root>/yard (scope-roots.sh --port-root); read only, never written.

WHY. A member laptop has no yard, and bin/member-standard.sh renders the project's AGENTS.md and CLAUDE.md from yard's own templates
(the kit items template.agents and template.claude), not from a copy typed here. The copy ships in vendor/scaffolder/, the way vendor/naming/
ships the naming package, so it can only change by this tool and a stale one is red.
Exit 0 current / written, 1 drift, 2 usage, 3 unchecked (no yard checkout: said in one line, never a pass).
EOF_USAGE
}
if command -v shasum >/dev/null 2>&1; then sha() { shasum -a 256 "$1" | cut -c1-64; }; else sha() { sha256sum "$1" | cut -c1-64; }; fi

MODE=''; Y=''
while [ $# -gt 0 ]; do
  case "$1" in
    --write|--check) MODE="$1" ;;
    --yard) [ $# -ge 2 ] || die "--yard takes a directory"; Y="$2"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done
[ -n "$MODE" ] || { usage >&2; exit 2; }
if [ -z "$Y" ]; then _pr="$(sh "$SRC/scope-roots.sh" --port-root 2>/dev/null)" || _pr=''; Y="${_pr:-$ROOT/..}/yard"; fi
if [ ! -d "$Y/templates/base" ]; then
  log_note "unchecked: no yard checkout at $Y (vendor/scaffolder is not compared; pass --yard <dir>)"; log_end || :; exit 3
fi
Y="$(CDPATH= cd -- "$Y" && pwd -P)"
for _f in $FILES; do [ -f "$Y/$_f" ] || die "yard has no $_f at $Y" "sh $0 $MODE --yard <a yard checkout>"; done

if [ "$MODE" = --write ]; then
  _commit="$(git -C "$Y" rev-parse HEAD 2>/dev/null || echo unknown)"
  rm -rf "$DEST.new"; mkdir -p "$DEST.new"
  {
    printf '# MANIFEST.tsv - GENERATED by bin/standard-vendor-scaffolder.sh, do not edit: re-run it (harbor#1278).\n'
    printf '# generated-by: sh bin/standard-vendor-scaffolder.sh --write\n# yard_commit: %s\n# columns: path\tsha256\tsource\n' "$_commit"
    for _f in $FILES; do
      mkdir -p "$DEST.new/${_f%/*}"; cp "$Y/$_f" "$DEST.new/$_f"
      printf '%s\t%s\t%s\n' "$_f" "$(sha "$DEST.new/$_f")" "in the scaffolder checkout: $_f"
    done
  } > "$DEST.new/MANIFEST.tsv"
  rm -rf "$DEST"; mv "$DEST.new" "$DEST"
  log_ok "vendored $(echo $FILES | wc -w | tr -d ' ') yard template(s) from yard ${_commit%"${_commit#???????}"} into $DEST"; log_end || :; exit 0
fi

[ -f "$MAN" ] || { log_fail "no $MAN: nothing is vendored here"; log_fix "sh $0 --write"; log_end || :; exit 1; }
DRIFT=0
bad() { DRIFT=$((DRIFT + 1)); log_fail "$1"; log_fix "sh $0 --write"; }
for _f in $FILES; do
  _row="$(grep "^$_f$TAB" "$MAN" | head -n 1)"; _h="$(printf '%s' "$_row" | cut -f2)"
  [ -n "$_row" ] || { bad "new $_f: yard carries it and the manifest has no row"; continue; }
  [ -f "$DEST/$_f" ] || { bad "missing vendor/scaffolder/$_f"; continue; }
  [ "$(sha "$DEST/$_f")" = "$_h" ] || bad "edited vendor/scaffolder/$_f: differs from its manifest row"
  [ "$(sha "$Y/$_f")" = "$_h" ] || bad "stale vendor/scaffolder/$_f: differs from yard now"
done
(cd "$DEST" 2>/dev/null && find . -type f ! -name MANIFEST.tsv | sed 's|^\./||') | while read -r _p; do
  case " $FILES " in *" $_p "*) ;; *) echo "extra $_p" ;; esac
done > "${TMPDIR:-/tmp}/svy.$$"
while read -r _k _r; do bad "$_k vendor/scaffolder/$_r: no manifest row names it"; done < "${TMPDIR:-/tmp}/svy.$$"; rm -f "${TMPDIR:-/tmp}/svy.$$"
if [ "$DRIFT" -eq 0 ]; then log_ok "vendor/scaffolder is current with yard ($(sed -n 's/^# yard_commit: *\(.......\).*/\1/p' "$MAN"))"; log_end || :; exit 0; fi
log_end || :; exit 1
