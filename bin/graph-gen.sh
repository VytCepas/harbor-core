import os, re, sys, json, hashlib, subprocess

def tilde(p, home):
    for h in home:
        if h and (p == h or p.startswith(h + '/')):
            return '~' + p[len(h):]
    return p

def git_index(root):
    """[(path, mode, blob)] of a checkout's index, or None when it is not one."""
    if not root or not os.path.isdir(root):
        return None
    r = subprocess.run(['git', '-C', root, 'ls-files', '-s', '-z'], capture_output=True)
    if r.returncode != 0:
        return None
    seen, out = set(), []
    for rec in r.stdout.split(b'\0'):
        if not rec:
            continue
        meta, path = rec.split(b'\t', 1)
        mode, blob, _stage = meta.split(b' ')
        if path in seen:
            continue
        seen.add(path)
        out.append((path.decode('utf-8', 'surrogateescape'), mode.decode(), blob.decode()))
    return out

def read_bytes(path, mode=''):
    try:
        if mode == '120000':
            return os.readlink(path).encode('utf-8', 'surrogateescape')
        with open(path, 'rb') as f:
            return f.read()
    except OSError:
        return None

def is_binary(b):   # git's own test: a NUL in the first 8000 bytes
    return b'\0' in b[:8000]

def trie_regex(words):
    """One lookahead regex that finds, at every offset, the LONGEST pattern starting there."""
    trie = {}
    for w in words:
        n = trie
        for c in w:
            n = n.setdefault(c, {})
        n[None] = True
    def emit(n):
        alts = [re.escape(bytes([c])) + emit(n[c]) for c in sorted(k for k in n if k is not None)]
        if not alts:
            return b''
        body = alts[0] if len(alts) == 1 else b'(?:' + b'|'.join(alts) + b')'
        if None in n:
            return b'(?:' + body + b')?'
        return body
    return re.compile(b'(?=(' + emit(trie) + b'))')

def scan(blob, rx, pats, prefixes):
    """Yield (line_no, node) for every pattern occurring in blob, overlapping, once per line."""
    for ln, line in enumerate(blob.split(b'\n'), 1):
        hit = set()
        for m in rx.finditer(line):
            for p in prefixes[m.group(1)]:
                hit.update(pats[p])
        for node in sorted(hit):
            yield ln, node

CODE_EXT = ('.sh', '.py', '.mjs', '.js', '.ts', '.awk')
RX_LOG = re.compile(rb'(?:^|[\s;&|({])log_init\s+([A-Za-z0-9_.-]+)')
RX_CHECK = re.compile(rb'\[check:([a-z0-9][a-z0-9._-]*)\]')
RX_TEST = re.compile(r'(^|/)(tests?|fixtures)/|(^|/)test_[^/]*$|[-_.]test\.[a-z]+$')
RX_GENBY = re.compile(rb'(?i)(?:generated by|regenerate with)\s+[`"(<*]*(?:sh\s+)?([A-Za-z0-9_][A-Za-z0-9_./-]*)')

# ── relations (harbor#996 G1, research/15 §3) ────────────────────────────────────────────────────────────
RX_ISSUE = re.compile(r'(?<![A-Za-z0-9_&#/.-])(?:([A-Za-z][A-Za-z0-9_-]*)#|#)([0-9]+)(?![0-9A-Za-z_])')
RX_DEC_S = re.compile(r'(?<![A-Za-z0-9_-])D-[0-9]+(?![0-9A-Za-z])')
RX_RECEIPT = re.compile(rb'(?:^|[\s;&|({])log_receipt\s+(?:"[^"]*"|\'[^\']*\'|\S+)\s+([a-z0-9][a-z0-9._-]*)')
RX_LETTER = re.compile(r'^rule_([A-Z][A-Z0-9]*)\(\) \{$')
RX_RULE = re.compile(r'^rule "([a-z][a-z0-9.-]*) ')
RX_MARKED = re.compile(r'\*\*([^*\n]+)\*\*|`([^`\n]+)`')
RX_ENFORC = re.compile(r'(?i)\benforc\w*')
RX_UNENFORCED = re.compile(r'(?i)\bnothing enforces (?:this|it)\b')
RX_TOKEN = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._:-]*$')
RX_SPAN = re.compile(r'`([^`\n]+)`')
RX_DISABLE = re.compile(r'\**\bDisable\b[^:|`]{0,40}:\**\s*(\S.*)$')   # `Disable:`, `**Disable:**`, `Disable the schedule:`
# notifies: CHECKS.md's notifies cell is prose, so a word in it names the channel. A closed set in code because
# terms.tsv has no channel class yet; whether it gets one is a registry decision (harbor#1026). A cell that
# names none of these is channel:other, still an edge: the row DID name where it notifies.
CHANNELS = (('desktop', r'\bdesktop\b|\bbanner\b'), ('statusline', r'\bstatusline\b|\bstatus line\b'),
            ('session', r'\bSessionStart\b|\bsystemMessage\b|\bthe tool call\b|\bthe session\b'),
            ('checks-log', r'checks\.log'), ('receipt', r'\breceipt\b|status\.json'), ('issue', r'\bissues?\b'),
            ('report', r'REPORT\.md|\bmorning report\b'),
            ('terminal', r'\bstdout\b|\bstderr\b|\bterminal\b|\bexit 1\b|\bsummary\b'))

def issues_in(s):
    """issue:<repo>#<n> for each issue reference; a bare #n is harbor's, since the rows read here are harbor's."""
    for m in RX_ISSUE.finditer(s):
        yield 'issue:%s#%s' % (m.group(1) or 'harbor', m.group(2))

def tsv_rows(data):
    """(line, {column: cell}) per data row of a registry TSV: `#` lines skipped, the row starting `id` is the header."""
    hdr, out = None, []
    for ln, line in enumerate(data.decode('utf-8', 'surrogateescape').split('\n'), 1):
        if not line.strip() or line.startswith('#'):
            continue
        c = line.split('\t')
        if hdr is None:
            hdr = c if c[0] == 'id' else None
            continue
        out.append((ln, dict(zip(hdr, c))))
    return out

def md_cells(line):
    """A markdown table row's cells: split on | outside backticks and not escaped."""
    cells, cur, tick, prev = [], [], False, ''
    for ch in line.strip():
        if ch == '`':
            tick = not tick
        if ch == '|' and not tick and prev != '\\':
            cells.append(''.join(cur).strip()); cur = []
        else:
            cur.append(ch)
        prev = ch
    cells.append(''.join(cur).strip())
    return cells[1:-1]

def md_section(lines, heading):
    """[(line, text)] of the lines under `## <heading>` up to the next `## `."""
    out, on = [], False
    for ln, s in enumerate(lines, 1):
        if s.startswith('## '):
            on = s[3:].strip() == heading
            continue
        if on:
            out.append((ln, s))
    return out

def md_table(lines, heading):
    """[(line, {column: cell})] of the table under `## <heading>`: its first | row is the header, |---| rows skipped."""
    hdr, out = None, []
    for ln, s in md_section(lines, heading):
        if not s.startswith('|'):
            continue
        c = md_cells(s)
        if hdr is None:
            hdr = [x.lower() for x in c]
        elif c and not set(c[0]) <= set('-: '):
            out.append((ln, dict(zip(hdr, c))))
    return out

def relate(t, texts, edges, root):
    """Add the relation edges of harbor's own tree; return the `# relation` rows: (name, source) per relation derived.
    A control is `control:<id>`. Every edge is read from a registry row, the wiring or the git history, never typed."""
    files = {p: m for p, m, _b in t['files']}
    txt = lambda p: texts.get(('harbor', p)) if p in files else None
    H = 'harbor:'
    rels, CTL = {}, 'standards/naming/controls.tsv'
    data = txt(CTL)
    if data is None:
        return []
    rows = tsv_rows(data)
    names = {}                     # a name a person writes for a control (id, emitted id, retired letter) -> nodes
    chk = {}                       # a check's CHECKS.md id (emitted, or its own id) -> nodes
    engines, controls = set(), set()
    for ln, d in rows:
        cid = d.get('id', '')
        if not cid:
            continue
        node, site = 'control:' + cid, H + CTL + ':%d' % ln
        controls.add(node)
        emitted = d.get('emitted', '-')
        for n in (cid, emitted):
            if n and n != '-':
                names.setdefault(n, set()).add(node)
        if d.get('type') == 'check':
            chk.setdefault(emitted if emitted not in ('', '-') else cid, set()).add(node)
        owner = d.get('owner', '-')
        if owner not in ('', '-'):
            edges.add(('owned-by', node, 'family:' + owner, site))
        for rp in re.split(r'[ ,]+', d.get('red_proof', '-')):
            if rp in files:
                edges.add(('red-proof', node, H + rp, site))
        eng = d.get('engine', '-')
        if eng in files and not eng.endswith('.md'):   # a markdown register lists a control; it runs nothing
            edges.add(('implements', H + eng, node, site))
            engines.add(eng)
        row = '\t'.join(d.get(k, '') for k in d if k != 'id')
        for dn in sorted(set(RX_DEC_S.findall(row))):
            edges.add(('enforces', node, 'decision:' + dn, site))
            edges.add(('enforced-by', 'decision:' + dn, node, site))
        for i in sorted(set(issues_in(row))):
            edges.add(('motivated-by', node, i, site))
    rels['owned-by'] = 'controls.tsv owner'
    rels['red-proof'] = 'controls.tsv red_proof, when that suite is tracked'
    # A retired letter id (`rule_C2() {` then `rule "git.no-ai-attribution …"`) is still how prose names a rule.
    for eng in sorted(engines):
        letter = None
        for line in (txt(eng) or b'').decode('utf-8', 'surrogateescape').split('\n'):
            m = RX_LETTER.match(line)
            if m:
                letter = m.group(1)
                continue
            m = RX_RULE.match(line.lstrip())
            if m and letter:
                names.setdefault(letter, set()).update(names.get(m.group(1), ()))
                letter = None
    # implements, from the wiring: code that stamps [check:<id>] or writes a receipt for it carries out that check
    for e, fr, to, site in sorted(edges):
        if e == 'emits' and to.startswith('check:') and to[6:] in chk:
            for n in chk[to[6:]]:
                edges.add(('implements', fr, n, site))
    receipts = 0
    for p, mode in sorted(files.items()):
        b = txt(p)
        if b is None or is_binary(b) or not ((mode == '100755' or p.endswith(CODE_EXT)) and not RX_TEST.search(p)):
            continue
        for ln, line in enumerate(b.split(b'\n'), 1):
            if line.lstrip().startswith(b'#'):
                continue
            for m in RX_RECEIPT.finditer(line):
                i = m.group(1).decode()
                for n in chk.get(i, ()):
                    edges.add(('implements', H + p, n, H + p + ':%d' % ln))
                    edges.add(('findings-land-in', n, 'finding:check/' + i, H + p + ':%d' % ln))
                    receipts += 1
    rels['implements'] = 'controls.tsv engine (code; a markdown register is not one), and code that stamps [check:<id>] or writes its receipt'
    # registered-in, notifies, disabled-by: CHECKS.md, the register of everything that runs on a schedule
    b = txt('CHECKS.md')
    if b is not None:
        lines = b.decode('utf-8', 'surrogateescape').split('\n')
        clause, plat = {}, {}
        for ln, row in md_table(lines, 'Register'):
            i = row.get('id', '').strip('`')
            site = H + 'CHECKS.md:%d' % ln
            for x in row.values():
                m = RX_DISABLE.search(x)
                if m:
                    clause.setdefault(i, (m.group(1).replace('**', '').strip(), site))
                    break
            for n in chk.get(i, ()):
                edges.add(('registered-in', n, H + 'CHECKS.md', site))
                cell = row.get('notifies', '').replace('*', '').strip()
                if not cell:
                    continue
                hit = ['none'] if re.match(r'\W*none\b', cell, re.I) else [ch for ch, rx in CHANNELS if re.search(rx, cell)]
                for ch in hit or ['other']:
                    edges.add(('notifies', n, 'channel:' + ch, site))
        rels['registered-in'] = 'CHECKS.md register rows, by the id the check prints'
        rels['notifies'] = "CHECKS.md's notifies column, by the channel it names"
        # disabled-by: each check's own row, never the `## Disable` template, which is a user agent's and so wrong for a
        # system daemon (`sudo launchctl bootout system/...`). The Platforms disable cell is a command per backtick span;
        # a cell with none ("the register row's own") defers to the register row's Disable clause, read whole, since
        # its spans mix commands with the files to delete.
        for ln, row in md_table(lines, 'Platforms'):
            cmds = RX_SPAN.findall(row.get('disable', ''))
            if cmds:
                plat[row.get('id', '').strip('`')] = (cmds, H + 'CHECKS.md:%d' % ln)
        for i in sorted(chk):
            if i in plat:
                cmds, site = plat[i]
            elif i in clause:
                cmds, site = [clause[i][0]], clause[i][1]
            else:
                continue
            for n in chk[i]:
                for cmd in cmds:
                    edges.add(('disabled-by', n, 'command:' + cmd, site))
        rels['disabled-by'] = "CHECKS.md's Platforms disable cell, one edge per command; a cell with none defers to the register row's Disable clause"
    # findings-land-in: the finding contract's HEAL rows are repairs (a receipt, above, is the issue store)
    b = txt('CONTRACTS/finding.md')
    if b is not None or receipts:
        on = False
        for ln, s in enumerate((b or b'').decode('utf-8', 'surrogateescape').split('\n'), 1):
            on = (on or '<!-- lanes:begin -->' in s) and '<!-- lanes:end -->' not in s
            c = md_cells(s) if on and s.startswith('|') else []
            if len(c) >= 4 and c[0] == 'HEAL':
                key, repair = c[1].strip('`'), c[3].strip('`')
                tier, _, i = key.partition('/')
                for n in (chk.get(i, ()) if tier == 'check' else names.get(i, ()) if tier == 'lint' else ()):
                    edges.add(('findings-land-in', n, 'command:' + repair, H + 'CONTRACTS/finding.md:%d' % ln))
        rels['findings-land-in'] = "a check's receipt (log_receipt: the finding store, CONTRACTS/finding.md) and that contract's HEAL repairs"
    # enforces and enforced-by: a D-n in a control's row (above), and a markdown line that says a control enforces it:
    # the control in bold or backticks, beside the word (`enforced by lint **C2**`, `**T1/T2/T3** enforce that`), never
    # past a sentence break. enforced-by is enforces read backward, so a clause's shape counts its own edges. Recorded
    # prose (vendor/, EVALS-DATA/) states no clause of harbor's.
    for p in sorted(files):
        if not p.endswith('.md') or p.startswith(('vendor/', 'EVALS-DATA/')):
            continue
        b = txt(p)
        if b is None or is_binary(b):
            continue
        for ln, s in enumerate(b.decode('utf-8', 'surrogateescape').split('\n'), 1):
            words = list(RX_ENFORC.finditer(s))
            if not words:
                continue
            site = H + p + ':%d' % ln
            if RX_UNENFORCED.search(s):
                edges.add(('enforced-by', H + p, 'judgment:unenforced', site))
            for m in RX_MARKED.finditer(s):
                gaps = [s[m.end():w.start()] if w.start() >= m.end() else s[w.end():m.start()] for w in words
                        if w.start() >= m.end() or m.start() >= w.end()]
                if not any(len(g) <= 24 and not re.search(r'[.;:|—]', g) for g in gaps):
                    continue
                for tok in re.split(r'[/,]', m.group(1) or m.group(2)):
                    tok = tok.strip()
                    if RX_TOKEN.match(tok):
                        for n in sorted(names.get(tok, ())):
                            edges.add(('enforces', n, H + p, site))
                            edges.add(('enforced-by', H + p, n, site))
    rels['enforces'] = 'a D-n in a controls.tsv row; a control named in bold or backticks on a markdown line about enforcement'
    rels['enforced-by'] = 'enforces read backward; "nothing enforces this" is judgment:unenforced'
    # motivated-by: the issues a control's row or a decision record cites, and the Refs trailers and subjects of the
    # commits that added or changed a control's row (research/15 R3: trailers alone were too few to read)
    for p in sorted(files):
        if p.startswith('docs/decisions/') and p.endswith('.md'):
            lines = (txt(p) or b'').decode('utf-8', 'surrogateescape').split('\n')
            alias = next((m.group(1) for m in (re.match(r'^alias: *(D-[0-9]+) *$', x) for x in lines[:12]) if m), None)
            if alias:
                for ln, s in enumerate(lines, 1):
                    for i in issues_in(s):
                        edges.add(('motivated-by', 'decision:' + alias, i, H + p + ':%d' % ln))
    r = subprocess.run(['git', '-C', root, 'log', '--no-merges', '-p', '--unified=0', '--no-color', '--no-ext-diff',
                        '--format=%x01%H%x02%s%x02%(trailers:key=Refs,valueonly,separator=%x2C)%x02', '--', CTL],
                       capture_output=True)
    commits = census = 0
    for chunk in r.stdout.decode('utf-8', 'surrogateescape').split('\x01')[1:] if r.returncode == 0 else []:
        sha, subj, refs, patch = (chunk.split('\x02', 3) + ['', '', ''])[:4]
        lines = patch.split('\n')
        # The commit that CREATES the file is a census, not a cause: harbor's (8951af6a, harbor#950) registered every
        # control that already ran, so it motivates no row.
        if any(x.startswith('new file mode') for x in lines):
            census += 1
            continue
        commits += 1
        why = sorted(set(issues_in(subj)) | set(issues_in(refs)))
        for line in lines if why else ():
            n = 'control:' + line[1:].split('\t', 1)[0]
            if line.startswith('+') and not line.startswith('+++') and n in controls:
                for i in why:
                    edges.add(('motivated-by', n, i, 'commit:' + sha[:12]))
    rels['motivated-by'] = ('issues cited in a controls.tsv row or a decision record; Refs trailers and subjects of the %d commits '
                            'that changed controls.tsv, not the %d that created it (a census)' % (commits, census))
    return sorted(rels.items())

def gen(a):
    out, home = a['out'], [a['home'], os.path.realpath(a['home'])]
    T = lambda p: tilde(p, home)
    trees = []     # dict(name, root, prefix, quals, files, unq_from)
    inputs, edges = [], set()

    def add_tree(name, root, prefix, quals, label):
        idx = git_index(root)
        if idx is None:
            inputs.append((label, T(root) if root else '-', 'absent'))
            return None
        t = dict(name=name, root=root, prefix=prefix, quals=quals, files=idx)
        trees.append(t)
        inputs.append((label, T(root), '%d files' % len(idx)))
        return t

    hq = os.path.basename(a['harbor_repo'].rstrip('/')) or 'harbor'
    harbor = add_tree('harbor', a['root'], 'harbor:', [hq + '/', 'harbor:'], 'harbor')
    for name, key in (('fleet', 'fleet'), ('yard', 'yard'), ('memory-store', 'memory_store')):
        r = a[key]
        q = os.path.basename(r.rstrip('/')) if r else name
        add_tree(name, r, name + ':', [q + '/', name + ':'], name)
    cfg = a['cfg']
    key = os.path.realpath(a['home']).replace('/', '-')
    notes_root = os.path.join(cfg, 'projects', key, 'memory')
    notes = add_tree('notes', notes_root, T(notes_root) + '/', ['memory/'], 'notes')

    # ── box nodes: pattern = the path after `~/`, so `/Users/x/.claude/bin/a.sh`, `~/.claude/bin/a.sh`
    # and `$HOME/.claude/bin/a.sh` all reach `~/.claude/bin/a.sh`.
    box_nodes = {}          # node -> pattern
    wiring = []             # (node, abspath) box files scanned for references
    def box(abspath):
        n = T(abspath)
        if n.startswith('~/'):
            box_nodes[n] = n[2:].encode('utf-8', 'surrogateescape')
        return n

    by_rel = {}             # (tree name, rel) -> node
    blob_of = {}            # blob -> [node]
    for t in trees:
        for p, mode, b in t['files']:
            by_rel[(t['name'], p)] = t['prefix'] + p
            blob_of.setdefault(b, []).append(t['prefix'] + p)
    canon = []              # (absolute deployed-from root, tree) for symlink resolution
    for t in trees:
        if t['name'] == 'harbor':
            canon.append((os.path.realpath(a['harbor_repo']), t))
        canon.append((os.path.realpath(t['root']), t))

    def blob_hash(b):
        return hashlib.sha1(b'blob %d\0' % len(b) + b).hexdigest()

    def source_for(rel, blob):
        for r in (rel, 'vendor/' + rel):
            if ('harbor', r) in by_rel:
                return [by_rel[('harbor', r)]]
        return sorted(set(blob_of.get(blob, [])))

    man = os.path.join(cfg, '.harbor-manifest')
    mb = read_bytes(man)
    if mb is None:
        inputs.append(('manifest', T(man), 'absent'))
    else:
        rows = unres = amb = 0
        for ln, line in enumerate(mb.decode('utf-8', 'surrogateescape').split('\n'), 1):
            f = line.split(' ')
            if line.startswith('#') or len(f) < 4:
                continue
            rows += 1
            dst = box(os.path.join(cfg, f[2]))
            src = source_for(f[2], f[0]) or ['?']
            unres += src == ['?']
            amb += len(src) > 1
            for s in src:   # byte-identical twins are each a source; the row says how many
                edges.add(('deploys_to', s, dst, T(man) + ':%d' % ln))
        inputs.append(('manifest', T(man), '%d rows, %d unresolved, %d from byte-identical twins' % (rows, unres, amb)))

    for s in ('settings.json', 'settings.local.json'):
        p = os.path.join(cfg, s)
        if os.path.isfile(p):
            wiring.append((box(p), p))
            hooks = cmds = 0
            try:
                for ev in json.load(open(p)).get('hooks', {}).values():
                    for grp in ev:
                        for h in grp.get('hooks', []):
                            hooks += 1
            except (ValueError, AttributeError, OSError):
                hooks = -1
            inputs.append(('settings', T(p), ('%d hook commands' % hooks) if hooks >= 0 else 'unparsable'))
        else:
            inputs.append(('settings', T(p), 'absent'))

    la = os.path.join(a['home'], 'Library', 'LaunchAgents')
    twins = {}
    for t in trees:
        for p, _m, _b in t['files']:
            if p.startswith('launchd/') and p.endswith('.plist') and p.count('/') == 1:
                twins.setdefault(p[len('launchd/'):], t['prefix'] + p)
    n_la = 0
    if os.path.isdir(la):
        for b in sorted(os.listdir(la)):
            if b in twins:
                p = os.path.join(la, b)
                dst = box(p)
                wiring.append((dst, p))
                edges.add(('deploys_to', twins[b], dst, dst))
                n_la += 1
        inputs.append(('launchagents', T(la), '%d with a tracked launchd/ twin' % n_la))
    else:
        inputs.append(('launchagents', T(la), 'absent'))

    lb = a['local_bin']
    n_lb = 0
    if lb and os.path.isdir(lb):
        for b in sorted(os.listdir(lb)):
            p = os.path.join(lb, b)
            src = None
            if os.path.islink(p):
                tgt = os.path.realpath(p)
                for r, t in canon:
                    if tgt.startswith(r + '/'):
                        rel = tgt[len(r) + 1:]
                        src = by_rel.get((t['name'], rel))
                        if src:
                            break
            elif os.path.isfile(p):
                data = read_bytes(p)
                c = sorted(set(blob_of.get(blob_hash(data), []))) if data is not None else []
                src = c[0] if len(c) == 1 else None
            if src:
                edges.add(('deploys_to', src, box(p), T(p)))
                n_lb += 1
        inputs.append(('local-bin', T(lb), '%d from a scanned tree' % n_lb))
    else:
        inputs.append(('local-bin', T(lb) if lb else '-', 'absent'))

    # ── emits and derives_from, from the repo trees' own files
    ids = set()
    texts = {}
    for t in trees:
        for p, mode, _b in t['files']:
            data = read_bytes(os.path.join(t['root'], p), mode)
            if data is not None:   # binary too: git grep -F reports a binary file that matches
                texts[(t['name'], p)] = data
    for t in trees:
        if t['name'] in ('memory-store', 'notes'):
            continue
        names = {}
        for p, _m, _b in t['files']:
            names.setdefault(os.path.basename(p), []).append(p)
        modes = {p: m for p, m, _b in t['files']}
        for p, mode, _b in t['files']:
            data = texts.get((t['name'], p))
            if data is None or is_binary(data):
                continue
            node = t['prefix'] + p
            # A test or fixture ASSERTS a stamp; the code under test is what emits it.
            code = (mode == '100755' or p.endswith(CODE_EXT)) and not RX_TEST.search(p)
            if code:
                for ln, line in enumerate(data.split(b'\n'), 1):
                    s = line.lstrip()
                    if s.startswith(b'#') or s.startswith(b'//'):
                        if ln <= 40 and b'GENERATED' in line:
                            for q in re.findall(rb'[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)+', line):
                                q = q.decode('utf-8', 'surrogateescape')
                                if (t['name'], q) in by_rel and q != p:
                                    edges.add(('derives_from', by_rel[(t['name'], q)], node, node + ':%d' % ln))
                        continue
                    for m in RX_LOG.finditer(line):
                        i = 'log:' + m.group(1).decode()
                        edges.add(('emits', node, i, node + ':%d' % ln))
                    for m in RX_CHECK.finditer(line):
                        i = 'check:' + m.group(1).decode()
                        ids.add(i)
                        edges.add(('emits', node, i, node + ':%d' % ln))
            for ln, line in enumerate(data.split(b'\n')[:10], 1):
                for m in RX_GENBY.finditer(line):
                    g = m.group(1).decode('utf-8', 'surrogateescape').rstrip('.')
                    if (t['name'], g) in by_rel:
                        gp = g
                    elif '/' not in g and len(names.get(g, [])) == 1:
                        gp = names[g][0]
                    else:
                        continue
                    if gp != p:
                        edges.add(('derives_from', node, t['prefix'] + gp, node + ':%d' % ln))

    # ── decisions (harbor#1029): D-n is an id, like check:<id>. The record whose `alias:` line says D-n defines
    # it; a citation anywhere in the tree is decided-by it; a record's `revised_by:` line is revised-by. Not a
    # source of decided-by: the records (their own text) and vendored text. (docs/index.html quoted every record, but it
    # is built, not tracked, since harbor#1197.) Same pattern as lint standard.decision-*.
    RX_DEC = re.compile(rb'(?<![A-Za-z0-9_-])D-[0-9]+(?![0-9A-Za-z])')
    RX_ALIAS = re.compile(rb'^alias: *(D-[0-9]+) *$')
    RX_REVBY = re.compile(rb'^revised_by: *(D-[0-9]+) *$')
    for t in trees:
        if t['name'] != 'harbor':
            continue
        for p, _m, _b in t['files']:
            data = texts.get((t['name'], p))
            if data is None or is_binary(data):
                continue
            node = t['prefix'] + p
            if p.startswith('docs/decisions/'):
                alias = revby = None
                for ln, line in enumerate(data.split(b'\n')[:12], 1):
                    m = RX_ALIAS.match(line.rstrip(b'\r'))
                    if m and alias is None:
                        alias = m.group(1).decode()
                        edges.add(('defines', node, 'decision:' + alias, node + ':%d' % ln))
                    m = RX_REVBY.match(line.rstrip(b'\r'))
                    if m and revby is None:
                        revby = (m.group(1).decode(), node + ':%d' % ln)
                if alias and revby:
                    edges.add(('revised-by', 'decision:' + alias, 'decision:' + revby[0], revby[1]))
                continue
            if p.startswith('vendor/') or p == 'CONTRACTS/decision-orphans.tsv':
                continue
            for ln, line in enumerate(data.split(b'\n'), 1):
                for m in RX_DEC.finditer(line):
                    edges.add(('decided-by', node, 'decision:' + m.group(0).decode(), node + ':%d' % ln))

    relations = relate(harbor, texts, edges, a['root']) if harbor else []

    # ── references: one pattern table per corpus
    shared = {}
    def put(d, pat, node):
        d.setdefault(pat, set()).add(node)
    for t in trees:
        for p, _m, _b in t['files']:
            for q in t['quals']:
                put(shared, (q + p).encode('utf-8', 'surrogateescape'), t['prefix'] + p)
    for n, pat in box_nodes.items():
        put(shared, pat, n)
    for i in ids:
        put(shared, i.encode(), i)
    def own(t):
        d = {}
        for p, _m, _b in t['files']:
            put(d, p.encode('utf-8', 'surrogateescape'), t['prefix'] + p)
        return d
    own_harbor = own(harbor) if harbor else {}

    def table(*ds):
        m = {}
        for d in ds:
            for k, v in d.items():
                m.setdefault(k, set()).update(v)
        pats = sorted(m)
        sp = set(pats)
        prefixes = {p: [p[:i] for i in range(1, len(p) + 1) if p[:i] in sp] for p in pats}
        return trie_regex(pats) if pats else None, m, prefixes

    def scan_into(src_node, data, tab):
        rx, pats, prefixes = tab
        if rx is None or data is None:
            return
        for ln, dst in scan(data, rx, pats, prefixes):
            edges.add(('references', src_node, dst, '%s:%d' % (src_node, ln)))

    for t in trees:
        tab = table(own(t), shared, own_harbor if t is notes else {})
        for p, _m, _b in t['files']:
            scan_into(t['prefix'] + p, texts.get((t['name'], p)), tab)
    if wiring:
        tab = table(own_harbor, shared)
        for n, p in sorted(wiring):
            scan_into(n, read_bytes(p), tab)

    with open(out, 'w', encoding='utf-8', errors='surrogateescape', newline='\n') as f:
        f.write('# graph.tsv (harbor#996) - generated by bin/graph-gen.sh; never edit, never commit\n')
        for label, where, status in inputs:
            f.write('# input\t%s\t%s\t%s\n' % (label, where, status))
        for name, source in relations:
            f.write('# relation\t%s\t%s\n' % (name, source))
        f.write('edge\tfrom\tto\tsite\n')
        key = lambda e: tuple(x.encode('utf-8', 'surrogateescape') for x in e)
        for e in sorted(edges, key=key):
            f.write('\t'.join(e) + '\n')

def refs(a):
    home = [a['home'], os.path.realpath(a['home'])]
    q = a['arg']
    if q.startswith('/'):
        q = tilde(q, home)
    rows = []
    with open(a['graph'], encoding='utf-8', errors='surrogateescape') as f:
        for line in f:
            if line.startswith('#') or line.startswith('edge\t'):
                continue
            rows.append(line.rstrip('\n').split('\t'))
    nodes = {r[1] for r in rows} | {r[2] for r in rows}
    ids = ('check:', 'log:', 'decision:', 'control:', 'issue:')
    known = ('harbor:', 'fleet:', 'yard:', 'memory-store:', 'family:', 'channel:', 'command:', 'finding:', 'judgment:') + ids
    if q.startswith('~/') or q.startswith(known):
        want = [q] if q in nodes else []
    elif os.path.exists(os.path.join(a['root'], q)) or 'harbor:' + q in nodes:
        want = ['harbor:' + q]
    else:
        want = sorted(n for n in nodes if n.startswith(ids) and n.split(':', 1)[1] == q)
    if not want:
        return 4
    roots = {}
    with open(a['graph'], encoding='utf-8', errors='surrogateescape') as f:
        for line in f:
            if line.startswith('# input\t'):
                _i, label, where, _st = line.rstrip('\n').split('\t')
                roots[label + ':'] = a['home'] + where[1:] if where.startswith('~/') else where
            elif not line.startswith('#'):
                break
    roots['harbor:'] = a['root']
    if a['sites'] == '1':
        sites = []
        for w in want:
            if w.startswith('decision:'):   # a decision's sites are its citing lines, which are harbor's
                pre, kinds = 'harbor:', ('decided-by',)
            else:
                pre, kinds = (w.split(':', 1)[0] + ':' if not w.startswith('~/') else None), ('references',)
            for e, fr, to, site in rows:
                if e in kinds and to == w and pre and fr.startswith(pre):
                    path, ln = site[len(pre):].rsplit(':', 1)
                    sites.append((path.encode('utf-8', 'surrogateescape'), int(ln), path, pre))
        done = set()
        for _b, ln, path, pre in sorted(set(sites)):
            data = read_bytes(os.path.join(roots.get(pre, ''), path))
            if data is not None and is_binary(data):   # git grep's own line for a binary match
                if path not in done:
                    sys.stdout.write('Binary file %s matches\n' % path)
                done.add(path)
            else:
                sys.stdout.write('%s:%d\n' % (path, ln))
        return 0
    hop = set(want)
    for e, fr, to, _s in rows:
        if e == 'deploys_to' and fr in want:
            hop.add(to)
    for r in rows:
        if r[1] in hop or r[2] in hop:
            sys.stdout.write('\t'.join(r) + '\n')
    return 0

if __name__ == '__main__':
    cmd, kv = sys.argv[1], dict(x.split('=', 1) for x in sys.argv[2:])
    sys.exit(gen(kv) or 0 if cmd == 'gen' else refs(kv))
PY
