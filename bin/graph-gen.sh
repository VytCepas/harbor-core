#!/usr/bin/env sh
# graph-gen.sh (harbor#996 A1, A2) — the reference graph: every path and id, and what points at it.
#
#   sh bin/graph-gen.sh                       write build/graph.tsv (untracked, like every build/ view)
#   sh bin/graph-gen.sh --check               exit 0 if build/graph.tsv equals a fresh build, 1 if stale or absent
#   sh bin/graph-gen.sh --stdout              print the graph and write nothing
#   sh bin/graph-gen.sh --refs <path|id>      every edge touching a node: what `harbor refs` runs
#   sh bin/graph-gen.sh --refs --sites <path> only the node's own-tree inbound sites, as path:line
#   options: --root <dir> (the harbor tree to scan; default this checkout) · --out <file> (default <root>/build/graph.tsv)
#   exit 0 ok · 1 stale, absent or no such node · 2 usage · 3 unchecked (no python3)
#
# THE EDGE TYPES, each derived from a source a person already maintains, never typed by hand:
#   references   a file's line holds another node's path as a literal substring. In its own tree a path
#                is unqualified (`bin/guard-bash.sh`); from another tree it is qualified, `<repo-dir>/<path>`
#                or `<system>:<path>`. Substring, not word, semantics, ON PURPOSE: it is the set
#                `git grep -n -F` finds, so `--refs --sites P` and `git grep -n -F P | cut -d: -f1,2` diff to
#                nothing, and a rename that rewrites the set leaves nothing behind (`bin/harbor` inside
#                `bin/harbor-clean.sh` is a reference, as it is to grep and to sed).
#   deploys_to   a tree's file → its copy on this box: the install manifest (~/.claude/.harbor-manifest),
#                ~/.local/bin entries, installed LaunchAgents with a tracked launchd/ twin.
#   derives_from a generated file → its generator: named in the file's first 10 lines ("generated by X",
#                "Regenerate with `sh X`"), or a generator's header comment naming the file GENERATED.
#   emits        a script → the id it stamps: `log_init <tool>` (log:<tool>), `[check:<id>]` (check:<id>).
#   defines      a decision record → its id: the `alias: D-<n>` line in docs/decisions/ (decision:D-<n>), harbor#1029.
#   decided-by   a line that cites D-<n> → decision:D-<n>, whether or not a record defines it (a dangling citation is
#                an edge, so `refs D-<n>` shows where it is). Vendored text and the records' own text are not sources.
#   revised-by   a record → the record that revises it: its `revised_by: D-<m>` line, decision:D-<n> → decision:D-<m>.
#   relations    implements, enforces, enforced-by, notifies, disabled-by, findings-land-in, owned-by, red-proof,
#                registered-in, motivated-by (harbor#996 G1; terms.tsv, class relation): a control is `control:<id>`, and
#                each edge is read from controls.tsv, CHECKS.md, the finding contract, the wiring (log_receipt,
#                [check:] stamps), a markdown line about enforcement, or the git history of controls.tsv.
#                Every relation derived is a `# relation` row naming its source; bin/standard-shape.sh judges
#                kinds.tsv's shapes over them, and a relation with no row is unchecked there, not absent.
#
# WHAT IT READS, and what it says when an input is absent: every input is a `# input` row at the top
# of the graph, read or absent, so a graph built in CI (no box, no siblings) says what it left out
# instead of reading as complete. The roots come from CONTRACTS/roots.tsv through roots.sh; the
# memory-store is the work-log checkout (HARBOR_LOG_DIR, worklog-push's own default), and the notes store
# is memory-route's key for $HOME.
#
# PYTHON, NOT AWK, and that is a fit decision: the core is an overlapping multi-pattern substring scan
# of ~5,000 paths over ~30 MB. `git grep -F -f <all paths>` took 154 s on this repo (measured
# 2026-10-05) and awk has no automaton; a trie-shaped regex in python3 does the harbor tree in under
# a second. python3 is already an optional dependency (`doctor.sh`); absent, this exits 3, unchecked.
#
# DETERMINISTIC: rows sorted bytewise, no clock, no absolute $HOME (rendered `~`). Same inputs, same bytes.
#
# DELIBERATELY ONE FILE (DOCTRINE/modularity.md): the build and the query share one node-naming rule
# (`<system>:path`, `~/…`, `check:`/`log:`) and one binary test; split, the query would carry a
# second copy of both, and a copy is what drifts.
