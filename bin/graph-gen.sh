    -h|--help) usage; exit 0 ;;
    -*) log_fail "unknown option $1"; log_fix "sh bin/graph-gen.sh --help"; log_end || :; exit 2 ;;
    *) [ "$MODE" = refs ] && [ -z "$ARG" ] || { log_fail "unexpected argument $1"; log_fix "sh bin/graph-gen.sh --help"; log_end || :; exit 2; }
