#!/usr/bin/env sh
# gate-codeowners.sh (harbor#1018) — .github/CODEOWNERS, DERIVED from the protected-paths register, so GitHub itself
# asks the operator's review for a protected change (with code-owner review required on main). Never hand-edited.
#
#   sh bin/gate-codeowners.sh --print            the file on stdout
#   sh bin/gate-codeowners.sh --check            exit 1 when .github/CODEOWNERS differs
#   sh bin/gate-codeowners.sh --write            rewrite it
#
# The owner is the owner of the repo .agents/ship.conf names. Always owned, whatever the register says: the register,
# ship.conf and .github/ (so CODEOWNERS owns itself). GitHub matches CODEOWNERS case-sensitively: the case-collision
# defence stays the local classifier's (gate-classify.sh).
set -eu
case "$0" in */*) HERE="${0%/*}" ;; *) HERE=. ;; esac
HERE="$(CDPATH='' cd -- "$HERE" && pwd)"; ROOT="$(CDPATH='' cd -- "$HERE/.." && pwd)"
LOG_FD=2
. "$HERE/library-log.sh"
log_init gate-codeowners
REG="$ROOT/.agents/protected-paths.tsv"; CONF="$ROOT/.agents/ship.conf"; OUT="$ROOT/.github/CODEOWNERS"
case "${1:-}" in
  --print|--check|--write) MODE="${1#--}" ;;
  -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) log_fail "a mode is required"; log_fix "sh $0 --check"; log_end || :; exit 2 ;;
esac
[ -f "$REG" ] || { log_fail "no register at $REG"; log_fix "git checkout the branch that carries .agents/protected-paths.tsv"; log_end || :; exit 1; }
REPO="$(awk '{ sub(/(^|[ \t])#.*/, "") } $1 == "repo" { print $2; exit }' "$CONF" 2>/dev/null)" || REPO=''
case "$REPO" in ?*/?*) OWNER="@${REPO%%/*}" ;; *) log_fail "$CONF names no repo"; log_fix "add: repo <owner>/<name>"; log_end || :; exit 1 ;; esac
T="$(mktemp -d "${TMPDIR:-/tmp}/codeowners.XXXXXX")"; trap 'rm -rf "$T"' EXIT

{
  printf '# GENERATED by bin/gate-codeowners.sh from .agents/protected-paths.tsv (harbor#1018). Do not edit:\n'
  printf '# change the register, then run: sh bin/gate-codeowners.sh --write\n'
  awk -F'\t' -v o="$OWNER" '/^#/ || NF < 2 || $1 == "glob" { next } !seen[$1]++ { print "/" $1 " " o }' "$REG"
  for _a in .agents/protected-paths.tsv .agents/ship.conf .github/; do printf '/%s %s\n' "$_a" "$OWNER"; done
} > "$T/new"

case "$MODE" in
  print) cat "$T/new"; exit 0 ;;
  check)
    if [ -f "$OUT" ] && cmp -s "$T/new" "$OUT"; then log_ok "$OUT is current ($(grep -vc '^#' "$T/new") rules)"; log_end; exit $?; fi
    log_fail "$OUT is missing or stale"; log_fix "sh $0 --write"; log_end || :; exit 1 ;;
esac
mkdir -p "$ROOT/.github"; cp "$T/new" "$OUT"
log_ok "wrote $(grep -vc '^#' "$T/new") rules to $OUT, owner $OWNER"
log_end
