#!/usr/bin/env sh
# library-bq.sh (harbor#1278) — what the hub loader (bq-load.sh) and the Mac's `harbor logs push` (bq-logs.sh) share: staging rows
# through bq-format.sh, the SQL that checks and merges them, and the load itself. Sourced; run alone it answers --help only. Sets -u, which both callers already hold.
#   bq_stage <dir> <table> <values.jsonl>   validate, keep the valid rows, code them into <dir>/staging/<table>.jsonl, count the rest
#                                            into <dir>/refused.json ({reason: n}); BQ_IN and BQ_OUT add up rows in and rows kept
#   bq_identity_scan <dir> <words-file>      exit 1 when any staged file holds a word of the file (the logins read) or an e-mail
#   bq_sql <dir> <project> <dataset>         the assertions and the one-transaction merge, on stdout
#   bq_apply <dir> <project> <dataset>       for each staged table: recreate stg_<table>, load it; then run bq_sql. Needs bq
# The merge replaces a person's rows whole for each (source, person_id, day) the load carries, so a replay never adds and no comment
# id is kept; it deletes every row of an excluded id (legal/dpia.md R12). BQ_ERASE names a file of such ids, 32 hex a line.
# GCP behaviour here (DELETE with a correlated EXISTS, ASSERT, multi-statement transactions) is as documented, not yet run (gcp-setup.md).
set -u  # what both callers already run under; -e stays theirs to set
BQ_HERE="${BQ_HERE:-$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)}"
command -v _log_line >/dev/null 2>&1 || . "$BQ_HERE/library-log.sh"
case "${0##*/}" in
  library-bq.sh) # run, not sourced: answer --help, refuse the rest
    case "${1:-}" in -h|--help) sed -n 2,11p "$0"; exit 0 ;; esac
    log_fail "library-bq.sh is a library: source it, never run it"; log_nofix "its header, with --help"; exit 2 ;;
esac

bq_stage() { # <dir> <table> <values.jsonl>
  mkdir -p "$1/staging"
  [ -f "$1/refused.json" ] || printf '{}' > "$1/refused.json"
  [ -s "$3" ] || return 0
  _bsn="$(grep -c . "$3" | tr -d ' ')"; BQ_IN=$((${BQ_IN:-0} + _bsn))
  sh "$BQ_HERE/bq-format.sh" row "$2" "$3" --keep "$1/$2.kept.jsonl" --counts "$1/$2.counts.json" >/dev/null 2>&1 || :
  [ -f "$1/$2.counts.json" ] || return 1
  jq -s -c '.[0] as $a | .[1] as $b | reduce ($b | keys[]) as $k ($a; .[$k] = ((.[$k] // 0) + $b[$k]))' "$1/refused.json" "$1/$2.counts.json" > "$1/refused.new" \
    && mv "$1/refused.new" "$1/refused.json"
  if [ -s "$1/$2.kept.jsonl" ]; then
    sh "$BQ_HERE/bq-format.sh" code "$2" "$1/$2.kept.jsonl" > "$1/staging/$2.jsonl" || return 1
    _bsk="$(grep -c . "$1/$2.kept.jsonl" | tr -d ' ')"; BQ_OUT=$((${BQ_OUT:-0} + _bsk))
  fi
  rm -f "$1/$2.kept.jsonl" "$1/$2.counts.json"
}

# bq_refuse <dir> <reason> <n>: rows refused before bq-format.sh saw them (no id, a bad comment, an excluded id)
bq_refuse() {
  [ "${3:-0}" -gt 0 ] || return 0
  [ -f "$1/refused.json" ] || printf '{}' > "$1/refused.json"
  jq -c --arg r "$2" --argjson n "$3" '.[$r] = ((.[$r] // 0) + $n)' "$1/refused.json" > "$1/refused.new" && mv "$1/refused.new" "$1/refused.json"
}

# Judged per value, not by grep: a short login is a substring of base64 often enough to make a text match a false alarm.
bq_identity_scan() { # <dir> <logins-file>
  for _bif in "$1"/staging/*.jsonl; do
    [ -f "$_bif" ] || continue
    _bih="$(jq -s --rawfile L "$2" '($L | split("\n") | map(select(length > 0) | ascii_downcase)) as $l
      | [.[] | .. | objects | to_entries[]
         | select((.key | test("^(member|author|login|user|email|_login)$"))
                  or ((.value | type) == "string" and ((.value | ascii_downcase) as $v | any($l[]; . == $v) or ($v | test("@")))))]
      | length' "$_bif")" || return 1
    [ "$_bih" -eq 0 ] || return 1
  done
  return 0
}

# the schema as "table field type set" lines, for the SQL below
_bq_fields() { awk -F'\t' '/^#/ || NF == 0 || $1 == "table" { next } { print $1 "\t" $2 "\t" $3 "\t" $4 }' "$BQ_HERE/../contracts/bq-schema.tsv"; }

bq_sql() { # <dir> <project> <dataset>
  _bq="\`$2.$3"
  printf -- '-- harbor logs merge (harbor#1278), generated by bin/library-bq.sh from contracts/bq-schema.tsv. One script: a failed ASSERT stops it.\n'
  printf "ASSERT (SELECT COUNT(*) FROM %s.INFORMATION_SCHEMA.COLUMNS\` WHERE data_type LIKE '%%STRING%%' AND NOT STARTS_WITH(table_name, 'dim_') AND NOT STARTS_WITH(table_name, 'stg_dim_')) = 0 AS 'a STRING column outside dim_';\n" "$_bq"
  for _bqs in "$1"/staging/*.jsonl; do
    [ -f "$_bqs" ] || continue
    _bqt="${_bqs##*/}"; _bqt="${_bqt%.jsonl}"
    case "$_bqt" in dim_*) continue ;; esac
    _bq_fields | awk -F'\t' -v t="$_bqt" -v d="$_bq" '$1 == t && ($3 == "code" || $3 == "codes") {
      n = split($4, s, "|"); in_s = ""; for (i = 1; i <= n; i++) in_s = in_s (i > 1 ? ", " : "") "'"'"'" s[i] "'"'"'"
      known = "(SELECT code FROM " d ".dim_enum` WHERE `set` IN (" in_s ") UNION ALL SELECT code FROM " d ".stg_dim_enum` WHERE `set` IN (" in_s "))"
      if ($3 == "code") w = "s." $2 " IS NOT NULL AND s." $2 " NOT IN " known
      else w = "c NOT IN " known
      from = d ".stg_" t "` s" ($3 == "codes" ? ", UNNEST(s." $2 ") c" : "")
      print "ASSERT NOT EXISTS (SELECT 1 FROM " from " WHERE " w ") AS '"'"'" t "." $2 ": a code dim_enum does not hold'"'"';"
    }'
  done
  printf 'BEGIN TRANSACTION;\n'
  [ ! -f "$1/staging/dim_enum.jsonl" ] || printf 'INSERT INTO %s.dim_enum` SELECT * FROM %s.stg_dim_enum` s WHERE NOT EXISTS (SELECT 1 FROM %s.dim_enum` d WHERE d.code = s.code);\n' "$_bq" "$_bq" "$_bq"
  [ ! -f "$1/staging/dim_policy.jsonl" ] || printf 'INSERT INTO %s.dim_policy` SELECT * FROM %s.stg_dim_policy` s WHERE NOT EXISTS (SELECT 1 FROM %s.dim_policy` d WHERE d.serial = s.serial);\n' "$_bq" "$_bq" "$_bq"
  for _bqt in $(_bq_fields | awk -F'\t' '$2 == "person_id" { print $1 }'); do
    [ -f "$1/staging/$_bqt.jsonl" ] || continue
    printf 'DELETE FROM %s.%s` t WHERE EXISTS (SELECT 1 FROM %s.stg_%s` s WHERE s.source = t.source AND s.person_id = t.person_id AND s.day = t.day);\n' "$_bq" "$_bqt" "$_bq" "$_bqt"
    printf 'INSERT INTO %s.%s` SELECT * FROM %s.stg_%s`;\n' "$_bq" "$_bqt" "$_bq" "$_bqt"
  done
  for _bqt in agg_approval ingest_audit ingest_refusal; do
    [ -f "$1/staging/$_bqt.jsonl" ] || continue
    [ "$_bqt" != agg_approval ] || printf 'DELETE FROM %s.agg_approval` t WHERE EXISTS (SELECT 1 FROM %s.stg_agg_approval` s WHERE s.source = t.source AND s.week = t.week);\n' "$_bq" "$_bq"
    printf 'INSERT INTO %s.%s` SELECT * FROM %s.stg_%s`;\n' "$_bq" "$_bqt" "$_bq" "$_bqt"
  done
  # an excluded id: every row of it goes, in every per-person table, whoever loaded it (R12)
  if [ -s "${BQ_ERASE:-}" ]; then
    _bqe="$(grep -E '^[0-9a-f]{32}$' "$BQ_ERASE" | sed "s/.*/FROM_HEX('&')/" | paste -s -d, -)"
    if [ -n "$_bqe" ]; then
      for _bqt in $(_bq_fields | awk -F'\t' '$2 == "person_id" { print $1 }'); do
        printf 'DELETE FROM %s.%s` WHERE person_id IN (%s);\n' "$_bq" "$_bqt" "$_bqe"
      done
    fi
  fi
  printf 'COMMIT TRANSACTION;\n'
}

bq_apply() { # <dir> <project> <dataset>
  command -v bq >/dev/null 2>&1 || { log_fail "bq is missing, so nothing was loaded"; log_fix "$(pkg_hint google-cloud-sdk)"; return 3; }
  for _bqs in "$1"/staging/*.jsonl; do
    [ -f "$_bqs" ] || continue
    _bqt="${_bqs##*/}"; _bqt="${_bqt%.jsonl}"
    sh "$BQ_HERE/bq-format.sh" bqschema "$_bqt" > "$1/$_bqt.schema.json" || return 1
    bq rm -f -t "$2:$3.stg_$_bqt" >/dev/null 2>&1 || :
    bq mk --table --expiration 86400 "$2:$3.stg_$_bqt" "$1/$_bqt.schema.json" >/dev/null || { log_fail "could not make stg_$_bqt"; log_nofix "gcp-setup.md, the dataset and the loader's role"; return 1; }
    bq load --source_format=NEWLINE_DELIMITED_JSON "$2:$3.stg_$_bqt" "$_bqs" >/dev/null || { log_fail "could not load stg_$_bqt"; log_nofix "bq show -j on the failed job"; return 1; }
  done
  bq_sql "$1" "$2" "$3" > "$1/merge.sql"
  bq query --use_legacy_sql=false --project_id="$2" < "$1/merge.sql" >/dev/null || { log_fail "the checks or the merge failed: nothing reached the fact tables"; log_nofix "$1/merge.sql and bq ls -j"; return 1; }
}
