#!/usr/bin/env sh
# scope-repos-generate.sh (GOVERNANCE, harbor#966; check id `scope.repos-generated`) - the files that list the repos are
# generated from the one registry, <private>/repos.tsv, so a rename is one row and the lists cannot drift from it.
#
#   sh scope-repos-generate.sh --projects      the project registry (<rules>/user/projects.tsv): governed rows that carry `covers`
#   sh scope-repos-generate.sh --roots         contracts/roots.tsv with the scaffolder and fleet-controller rows' paths taken from the registry (by kind)
#   sh scope-repos-generate.sh --fleet         the fleet controller's discovery stanza: the workspace root and every nested registered checkout
#   sh scope-repos-generate.sh --readme        the workspace README: each repo by domain, what it covers, where to start
#   sh scope-repos-generate.sh --out <dir>     all four, as projects.tsv, roots.tsv, fleet.yaml and README.md in <dir> (created); nothing else is written
#   sh scope-repos-generate.sh --check         each generated file against the one on this box; a delta is exit 1, one line per difference
#
# THE REGISTRY COLUMNS ARE contracts/private-layer.md's: governed (yes/no/-), domain, owner and covers are the four a row
# adds to the id, path, kind and remote. A registry with no governed row has nothing to generate from: --projects and --check
# stand down (exit 3, never a green) and say so. Bootstrap's clone list is NOT generated: deploy-bootstrap.sh reads the
# registry itself (--repo, --remote), and a second list would be a copy that can drift from the one it copies.
#
# Output lands on stdout or in --out: the registry names the operator's repos, so no generated file is ever written into
# core. Putting a file where it is read (the private layer, the workspace root, the fleet controller's checkout) is the
# operator's step, and --check is what says it was done. Exit 0 = nothing differs, 1 = a delta, 2 = a usage or registry
# error, 3 = it could not look (no registry, or no governed row yet).
set -u

case "$0" in */*) SRC="${0%/*}" ;; *) SRC=. ;; esac
ROOT="${HARBOR_SCOPE_ROOT:-$(CDPATH= cd -- "$SRC/.." && pwd)}"
# shellcheck disable=SC2034 # LOG_FD: read by library-log.sh
LOG_FD=2; . "$SRC/library-log.sh"; log_init scope-repos-generate
TAB="$(printf '\t')"

die() { log_fail "$1"; log_fix "${2:-sh $0 --help}"; log_end || :; exit 2; }
standdown() { log_note "$1"; log_note "this is not a pass: nothing was compared"; log_end || :; exit 3; }
SR() { sh "$SRC/scope-roots.sh" "$@"; }

MODE="${1:-}"
case "$MODE" in
  --projects|--roots|--fleet|--readme|--check) ;;
  --out) [ -n "${2:-}" ] || die "--out needs a directory" ;;
  -h|--help) sed -n '2,/^set -u/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) die "unknown argument '$MODE'" ;;
esac

RC=0
ROWS="$(SR --rows 2>"${TMPDIR:-/tmp}/scope-repos-generate.$$.err")" || RC=$?
ERRTXT="$(cat "${TMPDIR:-/tmp}/scope-repos-generate.$$.err" 2>/dev/null)"; rm -f "${TMPDIR:-/tmp}/scope-repos-generate.$$.err"
case "$RC" in
  0) ;;
  1) standdown "no repo registry on this box: ${ERRTXT:-scope-roots.sh --rows found none}" ;;
  *) die "the registry was refused: $ERRTXT" "sh $SRC/scope-roots.sh --registry-check" ;;
esac
PR="$(SR --port-root)" || die "scope-roots.sh could not resolve the workspace root" "sh $SRC/scope-roots.sh --port-root"
PR="${PR%/}"
case "$PR" in "${HOME:-/nonexistent}"/*) PRDISP="~/${PR#"$HOME"/}" ;; *) PRDISP="$PR" ;; esac

# Rows are id path kind remote topology interaction note domain governed owner covers (scope-roots.sh --rows).
GOVERNED="$(printf '%s\n' "$ROWS" | awk -F'\t' '$9 == "yes"')"

gen_projects() {
  cat <<'HDR'
# name<TAB>path<TAB>what it covers
# GENERATED by bin/scope-repos-generate.sh --projects from the private layer's repos.tsv. Edit the registry row, not this file.
# Read by project-pointer.sh at SessionStart. A new project is ONE ROW in repos.tsv: governed yes and a covers text.
#
# PATHS USE ~ AND NOT AN ABSOLUTE HOME. CONSTITUTION §3: this file is tracked in a repo and its content may leave the machine.
#
# KEEP `covers` SHORT AND SITUATIONAL. It is the only thing a session outside the repo will ever see about that project,
# and it is paid in every session. Say what question sends a reader there, not what the project is made of.
HDR
  printf '%s\n' "$GOVERNED" | awk -F'\t' -v b="$PRDISP" '$11 != "-" && NF >= 11 { printf "%s\t%s/%s\t%s\n", $1, b, $2, $11 }'
}

# The roots table with the paths of the registry-owned roles replaced. A role is found by KIND, exactly as scope-roots.sh
# --get finds it, and a kind with no row or two rows leaves the table's path (the rename window that lists both).
gen_roots() {
  _tbl="${HARBOR_SCOPE_ROOTS_TABLE:-$ROOT/contracts/roots.tsv}"
  [ -f "$_tbl" ] || die "no roots table at $_tbl" "git -C $ROOT status"
  _sc="$(printf '%s\n' "$ROWS" | awk -F'\t' '$3 == "scaffolder" { n++; p = $2 } END { if (n == 1) print p }')"
  _fc="$(printf '%s\n' "$ROWS" | awk -F'\t' '$3 == "fleet-controller" { n++; p = $2 } END { if (n == 1) print p }')"
  SC="$_sc" FC="$_fc" awk -F'\t' 'BEGIN { OFS = "\t"; sc = ENVIRON["SC"]; fc = ENVIRON["FC"] }
    /^#/ || NF < 4 || $1 == "var" { print; next }
    $2 == "REPOS" && sc != "" && ($1 == "HARBOR_SCOPE_SCAFFOLDER" || $1 == "PROJECT_INIT_SRC") { $3 = sc }
    $2 == "REPOS" && fc != "" && $1 == "HARBOR_SCOPE_FLEET_CONTROLLER" { $3 = fc }
    $2 == "REPOS" && fc != "" && $1 == "HARBOR_SCOPE_FLEET_FILE" { $3 = fc "/fleet.yaml" }
    { print }' "$_tbl"
}

gen_fleet() {
  printf '# fleet.yaml discovery stanza, GENERATED by bin/scope-repos-generate.sh --fleet from the private layer repos.tsv.\n'
  printf '# Depth-1 scanning of the workspace root finds every top-level checkout; `projects` names the ones it cannot see.\n'
  printf 'roots:\n  - %s\n' "$PR"
  _n="$(printf '%s\n' "$ROWS" | awk -F'\t' 'index($2, "/") > 0 { c++ } END { print c + 0 }')"
  if [ "$_n" -gt 0 ]; then
    printf 'projects:\n'
    printf '%s\n' "$ROWS" | awk -F'\t' -v r="$PR" 'index($2, "/") > 0 { printf "  - %s/%s\n", r, $2 }'
  fi
}

gen_readme() {
  cat <<'HDR'
# The workspace

GENERATED by `bin/scope-repos-generate.sh --readme` from the private layer's `repos.tsv`. Edit the registry row, not this file.

Each directory below is a registered repo. Anything else here is an unregistered tree: the workspace drift check
(`drift.port-root`, in the control plane's check register) lists it. Start in the control plane's `README.md`; each repo's own `README.md` routes from there.

HDR
  printf '%s\n' "$ROWS" | awk -F'\t' '{ d = ($8 == "-" ? "platform and unclassified" : $8); print d "\t" $0 }' | sort -t"$TAB" -k1,1 -k2,2 |
    awk -F'\t' '
      { d = $1; id = $2; path = $3; kind = $4; gov = $10; cv = $12
        if (d != last) { if (last != "") print ""; printf "## %s\n\n| Repo | Kind | Governed | What it covers |\n|---|---|---|---|\n", d; last = d }
        printf "| `%s` | %s | %s | %s |\n", path, kind, (gov == "-" ? "unknown" : gov), (cv == "-" ? "not yet written" : cv) }'
}

check_one() { # <label> <generated file> <on-disk file> <compare: rows|all> — prints one line per difference, returns 1 on a delta
  _lab="$1"; _gen="$2"; _disk="$3"; _cmp="$4"
  if [ ! -f "$_disk" ]; then printf '  ABSENT %s: %s is not there, so the registry has not been put in place\n' "$_lab" "$_disk"; return 1; fi
  if [ "$_cmp" = rows ]; then
    grep -v -E '^[[:space:]]*(#|$)' "$_gen" | sort > "$_gen.a"; grep -v -E '^[[:space:]]*(#|$)' "$_disk" | sort > "$_gen.b"
  else cp "$_gen" "$_gen.a"; cp "$_disk" "$_gen.b"; fi
  _age="$(find "$_disk" -mtime +0 -print 2>/dev/null | grep -c . || :)"
  if cmp -s "$_gen.a" "$_gen.b"; then printf '  ok     %s\n' "$_lab"; return 0; fi
  diff "$_gen.a" "$_gen.b" | awk -v l="$_lab" '/^< / { sub(/^< /, ""); printf "  DRIFT  %s: the registry says, the file lacks: %s\n", l, $0 }
                                               /^> / { sub(/^> /, ""); printf "  DRIFT  %s: the file has, the registry does not: %s\n", l, $0 }'
  [ "$_age" = 1 ] && printf '         (%s was last written more than a day ago)\n' "$_disk"
  return 1
}

case "$MODE" in
  --projects) [ -n "$GOVERNED" ] || standdown "no row of the registry is governed: yes, so there is nothing to put in a project registry"
              gen_projects ;;
  --roots) gen_roots ;;
  --fleet) gen_fleet ;;
  --readme) gen_readme ;;
  --out)
    [ -n "$GOVERNED" ] || standdown "no row of the registry is governed: yes, so the project registry would be empty"
    mkdir -p -- "$2" || die "cannot create $2"
    gen_projects > "$2/projects.tsv"; gen_roots > "$2/roots.tsv"; gen_fleet > "$2/fleet.yaml"; gen_readme > "$2/README.md"
    log_ok "wrote projects.tsv, roots.tsv, fleet.yaml and README.md to $2"; log_end || : ;;
  --check)
    [ -n "$GOVERNED" ] || standdown "no row of the registry is governed: yes, so the generated lists cannot be judged against it"
    W="$(mktemp -d "${TMPDIR:-/tmp}/scope-repos-generate.XXXXXX")" || die "cannot create a temp dir"
    trap 'rm -rf "$W"' EXIT INT TERM
    gen_projects > "$W/p"; gen_roots > "$W/r"; gen_fleet > "$W/f"; gen_readme > "$W/m"
    BAD=0
    _pf="$(SR --projects 2>/dev/null)" || _pf="$(SR --private)/context-rules/user/projects.tsv"
    check_one "project registry" "$W/p" "$_pf" rows || BAD=1
    check_one "roots table" "$W/r" "${HARBOR_SCOPE_ROOTS_TABLE:-$ROOT/contracts/roots.tsv}" rows || BAD=1
    check_one "workspace README" "$W/m" "$PR/README.md" all || BAD=1
    # The fleet stanza is judged for what it MUST name: a nested checkout the depth-1 scan cannot see. Extra projects are the fleet's own.
    _ff="$(SR --get HARBOR_SCOPE_FLEET_FILE 2>/dev/null || :)"
    if grep -q '^projects:' "$W/f"; then
      if [ -f "$_ff" ]; then
        grep '^  - /' "$W/f" | sort -u > "$W/f.a"; grep '^  - /' "$_ff" | sort -u > "$W/f.b"
        _miss="$(comm -23 "$W/f.a" "$W/f.b")"
        if [ -z "$_miss" ]; then printf '  ok     fleet discovery\n'
        else printf '%s\n' "$_miss" | sed 's/^  - /  DRIFT  fleet discovery: the fleet file does not list /'; BAD=1; fi
      else printf '  ABSENT fleet discovery: %s is not there\n' "${_ff:-the fleet file}"; BAD=1; fi
    else printf '  ok     fleet discovery (no nested checkout to name)\n'; fi
    if [ "$BAD" = 0 ]; then log_ok "every generated list matches the registry"; log_end || :; exit 0; fi
    log_fail "a generated list differs from the registry"
    log_fix "sh $0 --out <dir>, put each file where --check named it, and re-run"
    log_end || :; exit 1 ;;
esac
